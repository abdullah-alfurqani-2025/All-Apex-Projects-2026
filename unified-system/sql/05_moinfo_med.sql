-- التغطيات مع كل الأسماء وفريق العمل (بديل صفحتي Registration Events و Faceted Search)
CREATE OR REPLACE VIEW MOINFO_MED_V_COVERAGES AS
SELECT cv.COVERAGE_ID,
       cv.COVERAGE_DATE,
       EXTRACT(YEAR FROM cv.COVERAGE_DATE) AS COVERAGE_YEAR,
       cv.EVENT_ID,
       ev.NAME_AR AS EVENT_AR,
       cv.EVENT_TYPE_ID,
       typ.NAME_AR AS EVENT_TYPE_AR,
       w.GOVERNORATE_ID,
       g.NAME_AR AS GOVERNORATE_AR,
       cv.WILAYAT_ID,
       w.NAME_AR AS WILAYAT_AR,
       cv.PLACE_NAME,
       cv.CHANNEL_ID,
       ch.NAME_AR AS CHANNEL_AR,
       cv.PROGRAM_ID,
       pr.NAME_AR AS PROGRAM_AR,
       MOINFO_MED.GET_CREW_NAMES(cv.COVERAGE_ID, 'PHOTOGRAPHER') AS PHOTOGRAPHERS,
       MOINFO_MED.GET_CREW_NAMES(cv.COVERAGE_ID, 'EDITOR')       AS EDITORS,
       MOINFO_MED.GET_CREW_NAMES(cv.COVERAGE_ID, 'REPORTER')     AS REPORTERS,
       cv.REMARKS,
       cv.IS_ACTIVE,
       cv.CREATED_BY,
       cv.CREATED_AT,
       cv.UPDATED_BY,
       cv.UPDATED_AT
  FROM MOINFO_MED_COVERAGES cv
  LEFT JOIN MOINFO_LOOKUPS ev        ON ev.LOOKUP_ID = cv.EVENT_ID
  LEFT JOIN MOINFO_LOOKUPS typ       ON typ.LOOKUP_ID = cv.EVENT_TYPE_ID
  LEFT JOIN MOINFO_WILAYATS w        ON w.WILAYAT_ID = cv.WILAYAT_ID
  LEFT JOIN MOINFO_GOVERNORATES g    ON g.GOVERNORATE_ID = w.GOVERNORATE_ID
  LEFT JOIN MOINFO_MED_CHANNELS ch   ON ch.CHANNEL_ID = cv.CHANNEL_ID
  LEFT JOIN MOINFO_MED_PROGRAMS pr   ON pr.PROGRAM_ID = cv.PROGRAM_ID;

-- إحصائيات حسب السنة والقناة ونوع التغطية
-- (بديل الصفحة الرئيسية التي كانت تحسب 2020 إلى 2023 بأعمدة ثابتة)
CREATE OR REPLACE VIEW MOINFO_MED_V_STATS AS
SELECT EXTRACT(YEAR FROM cv.COVERAGE_DATE) AS COVERAGE_YEAR,
       ch.NAME_AR  AS CHANNEL_AR,
       typ.NAME_AR AS EVENT_TYPE_AR,
       COUNT(*)    AS COVERAGES_COUNT,
       SUM(CASE WHEN TRUNC(CAST(cv.CREATED_AT AS DATE)) = TRUNC(SYSDATE) THEN 1 ELSE 0 END) AS ADDED_TODAY
  FROM MOINFO_MED_COVERAGES cv
  LEFT JOIN MOINFO_MED_CHANNELS ch ON ch.CHANNEL_ID = cv.CHANNEL_ID
  LEFT JOIN MOINFO_LOOKUPS typ     ON typ.LOOKUP_ID = cv.EVENT_TYPE_ID
 WHERE cv.IS_ACTIVE = 'Y'
 GROUP BY EXTRACT(YEAR FROM cv.COVERAGE_DATE), ch.NAME_AR, typ.NAME_AR;

-- عدد التغطيات لكل موظف حسب السنة والدور
CREATE OR REPLACE VIEW MOINFO_MED_V_CREW_WORKLOAD AS
SELECT c.EMPLOYEE_ID,
       e.NAME_AR AS EMPLOYEE_NAME_AR,
       c.CREW_ROLE,
       CASE c.CREW_ROLE
           WHEN 'PHOTOGRAPHER' THEN 'مصور'
           WHEN 'EDITOR'       THEN 'مونتاج'
           WHEN 'REPORTER'     THEN 'مراسل'
       END AS CREW_ROLE_AR,
       EXTRACT(YEAR FROM cv.COVERAGE_DATE) AS COVERAGE_YEAR,
       COUNT(*) AS COVERAGES_COUNT
  FROM MOINFO_MED_CREW c
  JOIN MOINFO_MED_COVERAGES cv ON cv.COVERAGE_ID = c.COVERAGE_ID
  JOIN MOINFO_EMPLOYEES e      ON e.EMPLOYEE_ID = c.EMPLOYEE_ID
 WHERE cv.IS_ACTIVE = 'Y'
 GROUP BY c.EMPLOYEE_ID, e.NAME_AR, c.CREW_ROLE, EXTRACT(YEAR FROM cv.COVERAGE_DATE);


