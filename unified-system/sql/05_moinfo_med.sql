CREATE TABLE MOINFO_MED_CHANNELS (
    CHANNEL_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NAME_AR         VARCHAR2(150 CHAR)          NOT NULL,
    NAME_EN         VARCHAR2(150 CHAR),
    SORT_ORDER      NUMBER(6),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_MED_CHANNELS_PK PRIMARY KEY (CHANNEL_ID),
    CONSTRAINT MOINFO_MED_CHANNELS_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);

-- البرنامج يتبع قناة واحدة
CREATE TABLE MOINFO_MED_PROGRAMS (
    PROGRAM_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CHANNEL_ID      NUMBER                      NOT NULL,
    NAME_AR         VARCHAR2(150 CHAR)          NOT NULL,
    NAME_EN         VARCHAR2(150 CHAR),
    SORT_ORDER      NUMBER(6),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_MED_PROGRAMS_PK PRIMARY KEY (PROGRAM_ID),
    -- يُستخدم في القيد المركب أدناه لضمان أن البرنامج يتبع قناة التغطية نفسها
    CONSTRAINT MOINFO_MED_PROGRAMS_CH_UK UNIQUE (PROGRAM_ID, CHANNEL_ID),
    CONSTRAINT MOINFO_MED_PROGRAMS_CH_FK FOREIGN KEY (CHANNEL_ID) REFERENCES MOINFO_MED_CHANNELS (CHANNEL_ID),
    CONSTRAINT MOINFO_MED_PROGRAMS_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_MED_PROGRAMS_CH_IX ON MOINFO_MED_PROGRAMS (CHANNEL_ID);

CREATE TABLE MOINFO_MED_COVERAGES (
    COVERAGE_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    COVERAGE_DATE   DATE                        NOT NULL,
    EVENT_ID        NUMBER,
    EVENT_TYPE_ID   NUMBER,
    WILAYAT_ID      NUMBER,
    PLACE_NAME      VARCHAR2(250 CHAR),
    CHANNEL_ID      NUMBER,
    PROGRAM_ID      NUMBER,
    REMARKS         VARCHAR2(1000 CHAR),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_MED_COVERAGES_PK PRIMARY KEY (COVERAGE_ID),
    CONSTRAINT MOINFO_MED_COV_EVENT_FK FOREIGN KEY (EVENT_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_MED_COV_TYPE_FK FOREIGN KEY (EVENT_TYPE_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_MED_COV_WILAYAT_FK FOREIGN KEY (WILAYAT_ID) REFERENCES MOINFO_WILAYATS (WILAYAT_ID),
    CONSTRAINT MOINFO_MED_COV_CHANNEL_FK FOREIGN KEY (CHANNEL_ID) REFERENCES MOINFO_MED_CHANNELS (CHANNEL_ID),
    CONSTRAINT MOINFO_MED_COV_PROGRAM_FK FOREIGN KEY (PROGRAM_ID, CHANNEL_ID)
        REFERENCES MOINFO_MED_PROGRAMS (PROGRAM_ID, CHANNEL_ID),
    CONSTRAINT MOINFO_MED_COV_PROG_CH_CK CHECK (PROGRAM_ID IS NULL OR CHANNEL_ID IS NOT NULL),
    CONSTRAINT MOINFO_MED_COV_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_MED_COV_DATE_IX    ON MOINFO_MED_COVERAGES (COVERAGE_DATE);
CREATE INDEX MOINFO_MED_COV_EVENT_IX   ON MOINFO_MED_COVERAGES (EVENT_ID);
CREATE INDEX MOINFO_MED_COV_TYPE_IX    ON MOINFO_MED_COVERAGES (EVENT_TYPE_ID);
CREATE INDEX MOINFO_MED_COV_WILAYAT_IX ON MOINFO_MED_COVERAGES (WILAYAT_ID);
CREATE INDEX MOINFO_MED_COV_PROGRAM_IX ON MOINFO_MED_COVERAGES (PROGRAM_ID, CHANNEL_ID);

-- فريق التغطية: سطر لكل موظف ودوره (مصور، مونتاج، مراسل)
CREATE TABLE MOINFO_MED_CREW (
    CREW_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    COVERAGE_ID     NUMBER                      NOT NULL,
    CREW_ROLE       VARCHAR2(20)                NOT NULL,
    EMPLOYEE_ID     NUMBER                      NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_MED_CREW_PK PRIMARY KEY (CREW_ID),
    CONSTRAINT MOINFO_MED_CREW_UK UNIQUE (COVERAGE_ID, CREW_ROLE, EMPLOYEE_ID),
    CONSTRAINT MOINFO_MED_CREW_COV_FK FOREIGN KEY (COVERAGE_ID) REFERENCES MOINFO_MED_COVERAGES (COVERAGE_ID) ON DELETE CASCADE,
    CONSTRAINT MOINFO_MED_CREW_EMP_FK FOREIGN KEY (EMPLOYEE_ID) REFERENCES MOINFO_EMPLOYEES (EMPLOYEE_ID),
    CONSTRAINT MOINFO_MED_CREW_ROLE_CK CHECK (CREW_ROLE IN ('PHOTOGRAPHER', 'EDITOR', 'REPORTER'))
);
CREATE INDEX MOINFO_MED_CREW_EMP_IX ON MOINFO_MED_CREW (EMPLOYEE_ID);


--==============================================================================
-- 3) MOINFO_MED: فريق التغطية
--   في صفحة APEX يكون لكل دور عنصر اختيار متعدد (Popup LOV / Shuttle) من الموظفين:
--     مصدر العنصر  : RETURN MOINFO_MED.GET_CREW_IDS(:P3002_COVERAGE_ID, 'PHOTOGRAPHER');
--     بعد الحفظ     : MOINFO_MED.SET_CREW(:P3002_COVERAGE_ID, 'PHOTOGRAPHER', :P3002_PHOTOGRAPHERS);
--==============================================================================
CREATE OR REPLACE PACKAGE MOINFO_MED AS

    -- يستبدل أعضاء دور معيّن في التغطية بالقائمة المرسلة (أرقام موظفين مفصولة بـ :)
    PROCEDURE SET_CREW (
        p_coverage_id  IN NUMBER,
        p_crew_role    IN VARCHAR2,
        p_employee_ids IN VARCHAR2
    );

    -- أرقام الموظفين في الدور مفصولة بـ : (لتعبئة عنصر الاختيار المتعدد)
    FUNCTION GET_CREW_IDS (p_coverage_id IN NUMBER, p_crew_role IN VARCHAR2) RETURN VARCHAR2;

    -- أسماء الموظفين في الدور مفصولة بفاصلة (للتقارير)
    FUNCTION GET_CREW_NAMES (p_coverage_id IN NUMBER, p_crew_role IN VARCHAR2) RETURN VARCHAR2;

END MOINFO_MED;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_MED AS

    PROCEDURE SET_CREW (
        p_coverage_id  IN NUMBER,
        p_crew_role    IN VARCHAR2,
        p_employee_ids IN VARCHAR2
    ) IS
        l_role VARCHAR2(20)   := UPPER(p_crew_role);
        l_ids  APEX_T_NUMBER  := APEX_STRING.SPLIT_NUMBERS(p_employee_ids, ':');
    BEGIN
        DELETE FROM MOINFO_MED_CREW
         WHERE COVERAGE_ID = p_coverage_id
           AND CREW_ROLE = l_role
           AND EMPLOYEE_ID NOT IN (SELECT x.COLUMN_VALUE FROM TABLE(l_ids) x WHERE x.COLUMN_VALUE IS NOT NULL);

        INSERT INTO MOINFO_MED_CREW (COVERAGE_ID, CREW_ROLE, EMPLOYEE_ID)
        SELECT DISTINCT p_coverage_id, l_role, x.COLUMN_VALUE
          FROM TABLE(l_ids) x
         WHERE x.COLUMN_VALUE IS NOT NULL
           AND NOT EXISTS (SELECT 1
                             FROM MOINFO_MED_CREW c
                            WHERE c.COVERAGE_ID = p_coverage_id
                              AND c.CREW_ROLE = l_role
                              AND c.EMPLOYEE_ID = x.COLUMN_VALUE);
    END SET_CREW;

    FUNCTION GET_CREW_IDS (p_coverage_id IN NUMBER, p_crew_role IN VARCHAR2) RETURN VARCHAR2 IS
        l_list VARCHAR2(4000);
    BEGIN
        SELECT LISTAGG(EMPLOYEE_ID, ':') WITHIN GROUP (ORDER BY EMPLOYEE_ID)
          INTO l_list
          FROM MOINFO_MED_CREW
         WHERE COVERAGE_ID = p_coverage_id
           AND CREW_ROLE = UPPER(p_crew_role);
        RETURN l_list;
    END GET_CREW_IDS;

    FUNCTION GET_CREW_NAMES (p_coverage_id IN NUMBER, p_crew_role IN VARCHAR2) RETURN VARCHAR2 IS
        l_list VARCHAR2(4000);
    BEGIN
        SELECT LISTAGG(e.NAME_AR, '، ') WITHIN GROUP (ORDER BY e.NAME_AR)
          INTO l_list
          FROM MOINFO_MED_CREW c
          JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = c.EMPLOYEE_ID
         WHERE c.COVERAGE_ID = p_coverage_id
           AND c.CREW_ROLE = UPPER(p_crew_role);
        RETURN l_list;
    END GET_CREW_NAMES;

END MOINFO_MED;
