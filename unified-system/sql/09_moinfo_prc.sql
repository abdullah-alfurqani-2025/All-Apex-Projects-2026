-- رقم الطلب، والحالة الافتراضية DRAFT، والجهة الافتراضية جهة صاحب الطلب
CREATE OR REPLACE TRIGGER MOINFO_PRC_REQUESTS_DEF_BIU
BEFORE INSERT OR UPDATE OF REQUESTER_EMPLOYEE_ID, UNIT_ID ON MOINFO_PRC_REQUESTS
FOR EACH ROW
DECLARE
    l_prefix MOINFO_SETTINGS.SETTING_VALUE%TYPE;
BEGIN
    IF INSERTING THEN
        IF :NEW.STATUS_ID IS NULL THEN
            SELECT LOOKUP_ID INTO :NEW.STATUS_ID
              FROM MOINFO_LOOKUPS
             WHERE LOOKUP_TYPE = 'PRC_REQUEST_STATUS' AND LOOKUP_CODE = 'DRAFT';
        END IF;
        IF :NEW.REQUEST_NO IS NULL THEN
            BEGIN
                SELECT SETTING_VALUE INTO l_prefix FROM MOINFO_SETTINGS WHERE SETTING_KEY = 'PRC_REQUEST_NO_PREFIX';
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    l_prefix := 'PR';
            END;
            :NEW.REQUEST_NO := NVL(l_prefix, 'PR') || '-' || TO_CHAR(NVL(:NEW.REQUEST_DATE, SYSDATE), 'YYYY')
                               || '-' || LPAD(MOINFO_PRC_REQUEST_NO_SEQ.NEXTVAL, 5, '0');
        END IF;
    END IF;
    IF :NEW.UNIT_ID IS NULL AND :NEW.REQUESTER_EMPLOYEE_ID IS NOT NULL THEN
        SELECT MAX(UNIT_ID) INTO :NEW.UNIT_ID FROM MOINFO_EMPLOYEES WHERE EMPLOYEE_ID = :NEW.REQUESTER_EMPLOYEE_ID;
    END IF;
END;
/

-- الأصناف تُضاف وتُعدّل في المسودة فقط. بعد التقديم يُسمح بقرار الاعتماد على الصنف وحده.
-- (الحذف غير مقيّد هنا حتى لا يتعارض مع حذف الطلب بالتسلسل؛ الصفحات تمنعه بعد التقديم)
CREATE OR REPLACE TRIGGER MOINFO_PRC_ITEMS_LOCK_BIU
BEFORE INSERT OR UPDATE ON MOINFO_PRC_REQUEST_ITEMS
FOR EACH ROW
DECLARE
    l_status MOINFO_LOOKUPS.LOOKUP_CODE%TYPE;
BEGIN
    SELECT s.LOOKUP_CODE INTO l_status
      FROM MOINFO_PRC_REQUESTS r
      JOIN MOINFO_LOOKUPS s ON s.LOOKUP_ID = r.STATUS_ID
     WHERE r.REQUEST_ID = :NEW.REQUEST_ID;

    IF l_status = 'DRAFT' THEN
        RETURN;
    END IF;

    IF INSERTING THEN
        RAISE_APPLICATION_ERROR(-20051, 'لا يمكن إضافة أصناف بعد تقديم الطلب');
    END IF;

    IF l_status = 'SUBMITTED'
       AND :NEW.REQUEST_ID = :OLD.REQUEST_ID
       AND :NEW.ITEM_NAME = :OLD.ITEM_NAME
       AND :NEW.QUANTITY = :OLD.QUANTITY
       AND DECODE(:NEW.UNIT_PRICE, :OLD.UNIT_PRICE, 1, 0) = 1
       AND DECODE(:NEW.PRODUCT_TYPE_ID, :OLD.PRODUCT_TYPE_ID, 1, 0) = 1
       AND DECODE(:NEW.BRAND_ID, :OLD.BRAND_ID, 1, 0) = 1
       AND DECODE(:NEW.MODEL_ID, :OLD.MODEL_ID, 1, 0) = 1
       AND DECODE(:NEW.SUPPLIER_ID, :OLD.SUPPLIER_ID, 1, 0) = 1
       AND DECODE(:NEW.DESCRIPTION, :OLD.DESCRIPTION, 1, 0) = 1 THEN
        RETURN;  -- قرار الاعتماد على الصنف فقط
    END IF;

    RAISE_APPLICATION_ERROR(-20052, 'لا يمكن تعديل أصناف الطلب بعد تقديمه');
END;
/


--==============================================================================
-- 4) MOINFO_PRC: دورة الطلب والصلاحيات
--==============================================================================
CREATE OR REPLACE PACKAGE MOINFO_PRC AS

    -- رقم الحالة من رمزها، مثل STATUS_ID('DRAFT')
    FUNCTION STATUS_ID (p_code IN VARCHAR2) RETURN NUMBER;

    -- رمز حالة الطلب الحالية
    FUNCTION STATUS_CODE (p_request_id IN NUMBER) RETURN VARCHAR2;

    -- 'Y' إن كان يحق للمستخدم الحالي رؤية الطلب
    FUNCTION CAN_SEE (p_request_id IN NUMBER) RETURN VARCHAR2;

    -- 'Y' إن كان يحق له تعديل الطلب وأصنافه (مسودة، وهو صاحبه أو منشئه أو مشرف على جهته)
    FUNCTION CAN_EDIT (p_request_id IN NUMBER) RETURN VARCHAR2;

    -- 'Y' إن كان يحق له اعتماد الطلب أو رفضه (مقدَّم، ودوره MANAGER فأعلى على جهة الطلب)
    FUNCTION CAN_DECIDE (p_request_id IN NUMBER) RETURN VARCHAR2;

    -- 'Y' إن كان من قسم المشتريات (دور ADMIN في الوحدة PRC)
    FUNCTION IS_PURCHASER RETURN VARCHAR2;

    PROCEDURE SUBMIT    (p_request_id IN NUMBER);
    PROCEDURE APPROVE   (p_request_id IN NUMBER, p_reason IN VARCHAR2 DEFAULT NULL);
    PROCEDURE REJECT    (p_request_id IN NUMBER, p_reason IN VARCHAR2);
    PROCEDURE REOPEN    (p_request_id IN NUMBER);
    PROCEDURE CANCEL    (p_request_id IN NUMBER, p_reason IN VARCHAR2 DEFAULT NULL);
    PROCEDURE PURCHASE  (p_request_id IN NUMBER, p_date IN DATE DEFAULT TRUNC(SYSDATE), p_po_id IN NUMBER DEFAULT NULL);
    PROCEDURE DELIVER   (p_request_id IN NUMBER, p_date IN DATE DEFAULT TRUNC(SYSDATE));

END MOINFO_PRC;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_PRC AS

    FUNCTION STATUS_ID (p_code IN VARCHAR2) RETURN NUMBER IS
        l_id NUMBER;
    BEGIN
        SELECT LOOKUP_ID INTO l_id
          FROM MOINFO_LOOKUPS
         WHERE LOOKUP_TYPE = 'PRC_REQUEST_STATUS'
           AND LOOKUP_CODE = UPPER(p_code);
        RETURN l_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END STATUS_ID;

    FUNCTION STATUS_CODE (p_request_id IN NUMBER) RETURN VARCHAR2 IS
        l_code MOINFO_LOOKUPS.LOOKUP_CODE%TYPE;
    BEGIN
        SELECT s.LOOKUP_CODE INTO l_code
          FROM MOINFO_PRC_REQUESTS r
          JOIN MOINFO_LOOKUPS s ON s.LOOKUP_ID = r.STATUS_ID
         WHERE r.REQUEST_ID = p_request_id;
        RETURN l_code;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END STATUS_CODE;

    -- صاحب الطلب أو منشئه
    FUNCTION IS_OWNER (p_request_id IN NUMBER) RETURN BOOLEAN IS
        l_requester  NUMBER;
        l_created_by VARCHAR2(255);
        l_my_emp     NUMBER := MOINFO_HR.MY_EMPLOYEE_ID;
        l_me         VARCHAR2(255) := UPPER(TRIM(V('APP_USER')));
    BEGIN
        SELECT REQUESTER_EMPLOYEE_ID, CREATED_BY
          INTO l_requester, l_created_by
          FROM MOINFO_PRC_REQUESTS
         WHERE REQUEST_ID = p_request_id;
        RETURN (l_my_emp IS NOT NULL AND l_requester = l_my_emp) OR UPPER(l_created_by) = l_me;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN FALSE;
    END IS_OWNER;

    FUNCTION REQUEST_UNIT (p_request_id IN NUMBER) RETURN NUMBER IS
        l_unit NUMBER;
    BEGIN
        SELECT UNIT_ID INTO l_unit FROM MOINFO_PRC_REQUESTS WHERE REQUEST_ID = p_request_id;
        RETURN l_unit;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END REQUEST_UNIT;

    FUNCTION CAN_SEE (p_request_id IN NUMBER) RETURN VARCHAR2 IS
        l_scope VARCHAR2(10);
    BEGIN
        l_scope := MOINFO_SEC.DATA_SCOPE('PRC');
        IF l_scope = 'ALL' THEN
            RETURN 'Y';
        ELSIF l_scope IS NULL THEN
            RETURN 'N';
        END IF;
        IF IS_OWNER(p_request_id) THEN
            RETURN 'Y';
        END IF;
        IF l_scope = 'UNIT' THEN
            RETURN MOINFO_SEC.CAN_SEE_UNIT('PRC', REQUEST_UNIT(p_request_id));
        END IF;
        RETURN 'N';
    END CAN_SEE;

    FUNCTION CAN_EDIT (p_request_id IN NUMBER) RETURN VARCHAR2 IS
    BEGIN
        IF NVL(STATUS_CODE(p_request_id), 'X') <> 'DRAFT' THEN
            RETURN 'N';
        END IF;
        IF IS_OWNER(p_request_id) THEN
            RETURN 'Y';
        END IF;
        IF MOINFO_SEC.HAS_ROLE('PRC', 'MANAGER') AND CAN_SEE(p_request_id) = 'Y' THEN
            RETURN 'Y';
        END IF;
        RETURN 'N';
    END CAN_EDIT;

    FUNCTION CAN_DECIDE (p_request_id IN NUMBER) RETURN VARCHAR2 IS
    BEGIN
        IF NVL(STATUS_CODE(p_request_id), 'X') <> 'SUBMITTED' THEN
            RETURN 'N';
        END IF;
        IF MOINFO_SEC.HAS_ROLE('PRC', 'MANAGER')
           AND MOINFO_SEC.CAN_SEE_UNIT('PRC', REQUEST_UNIT(p_request_id)) = 'Y' THEN
            RETURN 'Y';
        END IF;
        RETURN 'N';
    END CAN_DECIDE;

    FUNCTION IS_PURCHASER RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN MOINFO_SEC.HAS_ROLE('PRC', 'ADMIN') THEN 'Y' ELSE 'N' END;
    END IS_PURCHASER;

    -- ينقل الطلب من إحدى الحالات المسموحة إلى حالة جديدة، أو يرفض الانتقال
    PROCEDURE MOVE (p_request_id IN NUMBER, p_from IN VARCHAR2, p_to IN VARCHAR2) IS
        l_code VARCHAR2(50) := STATUS_CODE(p_request_id);
        l_to   NUMBER := STATUS_ID(p_to);
    BEGIN
        IF l_code IS NULL THEN
            RAISE_APPLICATION_ERROR(-20053, 'طلب الشراء غير موجود');
        END IF;
        IF INSTR(',' || p_from || ',', ',' || l_code || ',') = 0 THEN
            RAISE_APPLICATION_ERROR(-20054, 'لا يمكن تنفيذ هذا الإجراء على طلب حالته الحالية ' || l_code);
        END IF;
        UPDATE MOINFO_PRC_REQUESTS SET STATUS_ID = l_to WHERE REQUEST_ID = p_request_id;
    END MOVE;

    PROCEDURE SUBMIT (p_request_id IN NUMBER) IS
        l_n NUMBER;
    BEGIN
        IF CAN_EDIT(p_request_id) = 'N' THEN
            RAISE_APPLICATION_ERROR(-20055, 'لا تملك صلاحية تقديم هذا الطلب');
        END IF;
        SELECT COUNT(*) INTO l_n FROM MOINFO_PRC_REQUEST_ITEMS WHERE REQUEST_ID = p_request_id;
        IF l_n = 0 THEN
            RAISE_APPLICATION_ERROR(-20056, 'أضف صنفًا واحدًا على الأقل قبل تقديم الطلب');
        END IF;
        MOVE(p_request_id, 'DRAFT', 'SUBMITTED');
        UPDATE MOINFO_PRC_REQUESTS
           SET SUBMITTED_AT = SYSTIMESTAMP, DECIDED_BY = NULL, DECIDED_AT = NULL, DECISION_REASON = NULL
         WHERE REQUEST_ID = p_request_id;
    END SUBMIT;

    PROCEDURE DECIDE (p_request_id IN NUMBER, p_to IN VARCHAR2, p_reason IN VARCHAR2) IS
    BEGIN
        IF CAN_DECIDE(p_request_id) = 'N' THEN
            RAISE_APPLICATION_ERROR(-20057, 'لا تملك صلاحية اعتماد هذا الطلب أو رفضه');
        END IF;
        MOVE(p_request_id, 'SUBMITTED', p_to);
        UPDATE MOINFO_PRC_REQUESTS
           SET DECIDED_BY = V('APP_USER'), DECIDED_AT = SYSTIMESTAMP, DECISION_REASON = p_reason
         WHERE REQUEST_ID = p_request_id;
    END DECIDE;

    PROCEDURE APPROVE (p_request_id IN NUMBER, p_reason IN VARCHAR2 DEFAULT NULL) IS
        l_n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO l_n
          FROM MOINFO_PRC_REQUEST_ITEMS
         WHERE REQUEST_ID = p_request_id AND NVL(IS_APPROVED, 'Y') = 'Y';
        IF l_n = 0 THEN
            RAISE_APPLICATION_ERROR(-20058, 'كل الأصناف مرفوضة. ارفض الطلب بدل اعتماده');
        END IF;
        -- الأصناف التي لم يُتخذ فيها قرار تُعتمد مع الطلب (قبل تغيير الحالة، لأن Trigger الأصناف يسمح بذلك في SUBMITTED)
        UPDATE MOINFO_PRC_REQUEST_ITEMS SET IS_APPROVED = 'Y'
         WHERE REQUEST_ID = p_request_id AND IS_APPROVED IS NULL;
        DECIDE(p_request_id, 'APPROVED', p_reason);
    END APPROVE;

    PROCEDURE REJECT (p_request_id IN NUMBER, p_reason IN VARCHAR2) IS
    BEGIN
        IF TRIM(p_reason) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20059, 'اكتب سبب الرفض');
        END IF;
        DECIDE(p_request_id, 'REJECTED', p_reason);
    END REJECT;

    -- الطلب المرفوض يعود مسودة ليعدّله صاحبه ويقدّمه مرة أخرى
    PROCEDURE REOPEN (p_request_id IN NUMBER) IS
    BEGIN
        IF NOT IS_OWNER(p_request_id) AND NOT MOINFO_SEC.HAS_ROLE('PRC', 'MANAGER') THEN
            RAISE_APPLICATION_ERROR(-20060, 'لا تملك صلاحية إعادة الطلب إلى مسودة');
        END IF;
        MOVE(p_request_id, 'REJECTED', 'DRAFT');
        UPDATE MOINFO_PRC_REQUEST_ITEMS SET IS_APPROVED = NULL, REJECT_REASON = NULL WHERE REQUEST_ID = p_request_id;
    END REOPEN;

    PROCEDURE CANCEL (p_request_id IN NUMBER, p_reason IN VARCHAR2 DEFAULT NULL) IS
    BEGIN
        IF NOT IS_OWNER(p_request_id) AND IS_PURCHASER = 'N' AND CAN_DECIDE(p_request_id) = 'N' THEN
            RAISE_APPLICATION_ERROR(-20061, 'لا تملك صلاحية إلغاء هذا الطلب');
        END IF;
        MOVE(p_request_id, 'DRAFT,SUBMITTED,APPROVED', 'CANCELLED');
        IF p_reason IS NOT NULL THEN
            UPDATE MOINFO_PRC_REQUESTS SET DECISION_REASON = p_reason WHERE REQUEST_ID = p_request_id;
        END IF;
    END CANCEL;

    PROCEDURE PURCHASE (p_request_id IN NUMBER, p_date IN DATE DEFAULT TRUNC(SYSDATE), p_po_id IN NUMBER DEFAULT NULL) IS
    BEGIN
        IF IS_PURCHASER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20062, 'تسجيل الشراء لقسم المشتريات');
        END IF;
        MOVE(p_request_id, 'APPROVED', 'PURCHASED');
        UPDATE MOINFO_PRC_REQUESTS
           SET PURCHASED_DATE = NVL(p_date, TRUNC(SYSDATE)), PO_ID = NVL(p_po_id, PO_ID)
         WHERE REQUEST_ID = p_request_id;
    END PURCHASE;

    PROCEDURE DELIVER (p_request_id IN NUMBER, p_date IN DATE DEFAULT TRUNC(SYSDATE)) IS
    BEGIN
        IF IS_PURCHASER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20063, 'تسجيل الاستلام لقسم المشتريات');
        END IF;
        MOVE(p_request_id, 'PURCHASED', 'DELIVERED');
        UPDATE MOINFO_PRC_REQUESTS
           SET DELIVERED_DATE = GREATEST(NVL(p_date, TRUNC(SYSDATE)), NVL(PURCHASED_DATE, DATE '1900-01-01'))
         WHERE REQUEST_ID = p_request_id;
    END DELIVER;

END MOINFO_PRC;
