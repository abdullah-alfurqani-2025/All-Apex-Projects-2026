CREATE OR REPLACE VIEW MOINFO_PRC_V_ITEMS AS
SELECT i.ITEM_ID,
       i.REQUEST_ID,
       i.ITEM_NAME,
       i.PRODUCT_TYPE_ID,
       t.NAME_AR AS PRODUCT_TYPE_AR,
       i.BRAND_ID,
       b.NAME AS BRAND_NAME,
       i.MODEL_ID,
       m.NAME AS MODEL_NAME,
       i.SUPPLIER_ID,
       s.NAME_AR AS SUPPLIER_AR,
       i.DESCRIPTION,
       i.QUANTITY,
       i.UNIT_PRICE,
       i.LINE_TOTAL,
       i.IS_APPROVED,
       CASE i.IS_APPROVED WHEN 'Y' THEN 'معتمد' WHEN 'N' THEN 'مرفوض' END AS APPROVAL_AR,
       i.REJECT_REASON,
       i.SORT_ORDER
  FROM MOINFO_PRC_REQUEST_ITEMS i
  LEFT JOIN MOINFO_CAT_PRODUCT_TYPES t ON t.PRODUCT_TYPE_ID = i.PRODUCT_TYPE_ID
  LEFT JOIN MOINFO_CAT_BRANDS b        ON b.BRAND_ID = i.BRAND_ID
  LEFT JOIN MOINFO_CAT_MODELS m        ON m.MODEL_ID = i.MODEL_ID
  LEFT JOIN MOINFO_CAT_SUPPLIERS s     ON s.SUPPLIER_ID = i.SUPPLIER_ID;

CREATE OR REPLACE VIEW MOINFO_PRC_V_REQUESTS AS
SELECT r.REQUEST_ID,
       r.REQUEST_NO,
       r.SUBJECT,
       r.REQUEST_DATE,
       r.REQUESTER_EMPLOYEE_ID,
       e.NAME_AR AS REQUESTER_AR,
       e.EMPLOYEE_NO AS REQUESTER_NO,
       r.UNIT_ID,
       u.UNIT_PATH_AR AS UNIT_AR,
       r.STATUS_ID,
       st.LOOKUP_CODE AS STATUS_CODE,
       st.NAME_AR AS STATUS_AR,
       r.JUSTIFICATION,
       r.SUBMITTED_AT,
       r.DECIDED_BY,
       NVL(du.DISPLAY_NAME, r.DECIDED_BY) AS DECIDED_BY_NAME,
       r.DECIDED_AT,
       r.DECISION_REASON,
       r.PO_ID,
       po.PO_NO,
       r.PURCHASED_DATE,
       r.DELIVERED_DATE,
       r.REMARKS,
       r.IS_ACTIVE,
       NVL(it.ITEMS_COUNT, 0) AS ITEMS_COUNT,
       NVL(it.TOTAL_QTY, 0) AS TOTAL_QTY,
       it.TOTAL_AMOUNT,
       it.APPROVED_AMOUNT,
       r.CREATED_BY,
       r.CREATED_AT
  FROM MOINFO_PRC_REQUESTS r
  JOIN MOINFO_LOOKUPS st                ON st.LOOKUP_ID = r.STATUS_ID
  JOIN MOINFO_EMPLOYEES e               ON e.EMPLOYEE_ID = r.REQUESTER_EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS u            ON u.UNIT_ID = r.UNIT_ID
  LEFT JOIN MOINFO_USERS du             ON du.USERNAME = r.DECIDED_BY
  LEFT JOIN MOINFO_HD_PURCHASE_ORDERS po ON po.PO_ID = r.PO_ID
  LEFT JOIN (SELECT REQUEST_ID,
                    COUNT(*) AS ITEMS_COUNT,
                    SUM(QUANTITY) AS TOTAL_QTY,
                    SUM(LINE_TOTAL) AS TOTAL_AMOUNT,
                    SUM(CASE WHEN NVL(IS_APPROVED, 'Y') = 'Y' THEN LINE_TOTAL END) AS APPROVED_AMOUNT
               FROM MOINFO_PRC_REQUEST_ITEMS
              GROUP BY REQUEST_ID) it ON it.REQUEST_ID = r.REQUEST_ID;

-- إحصائيات حسب الشهر والجهة والحالة
CREATE OR REPLACE VIEW MOINFO_PRC_V_STATS AS
SELECT TRUNC(r.REQUEST_DATE, 'MM') AS REQUEST_MONTH,
       r.UNIT_ID,
       r.UNIT_AR,
       r.STATUS_CODE,
       r.STATUS_AR,
       COUNT(*) AS REQUESTS_COUNT,
       SUM(r.ITEMS_COUNT) AS ITEMS_COUNT,
       SUM(r.TOTAL_AMOUNT) AS TOTAL_AMOUNT,
       SUM(r.APPROVED_AMOUNT) AS APPROVED_AMOUNT
  FROM MOINFO_PRC_V_REQUESTS r
 WHERE r.IS_ACTIVE = 'Y'
 GROUP BY TRUNC(r.REQUEST_DATE, 'MM'), r.UNIT_ID, r.UNIT_AR, r.STATUS_CODE, r.STATUS_AR;


