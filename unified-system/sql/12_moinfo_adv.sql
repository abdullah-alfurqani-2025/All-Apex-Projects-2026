    CONSTRAINT MOINFO_ADV_ACC_AGENCY_CK CHECK (AGENCY_ID IS NULL OR (ACCOUNT_TYPE = 'COMPANY' AND AGENCY_ID <> ACCOUNT_ID)),
    CONSTRAINT MOINFO_ADV_ACC_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
