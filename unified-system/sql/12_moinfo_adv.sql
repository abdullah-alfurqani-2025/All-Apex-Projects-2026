-- السكربت 12: القسم التجاري (ADV) — بديل Commercial Department System (f400)
--
-- يُشغَّل بعد 01 إلى 11 في نفس الـ Schema.
--
-- النظام القديم فيه مساران متوازيان بجداول مكررة:
--   المعلنون المباشرون: PRT_ADV_COMPANIES ← PRT_ADV_CONTACT ← PRT_ADV_ADVERTISEMENT
--   الوكالات:           PRT_ADV_AGENCIES ← PRT_ADV_AGENCYCLIENTS ← PRT_ADV_ADVERTISEMENTS، وPRT_ADV_CONTACTS
-- يُدمجان هنا:
--   PRT_ADV_COMPANIES + PRT_ADV_AGENCIES + PRT_ADV_AGENCYCLIENTS ← MOINFO_ADV_ACCOUNTS
--       (نوع الحساب COMPANY أو AGENCY، وعميل الوكالة = شركة معلنة يمثّلها وكيل AGENCY_ID)
--   PRT_ADV_CONTACT + PRT_ADV_CONTACTS            ← MOINFO_ADV_CONTACTS (جهة اتصال لأي حساب)
--   PRT_ADV_ADVERTISEMENT + PRT_ADV_ADVERTISEMENTS ← MOINFO_ADV_DEALS (فرصة إعلانية للمعلن، عبر وكالة أو مباشرة)
--   FOLLOWUP / FOLLOWSUP                           ← MOINFO_ADV_ACTIVITIES (سجل متابعة بدل حقل نصي واحد)
--   PRT_ADV_SECTOR / INDUSTRIES / MEDIA            ← MOINFO_LOOKUPS (ADV_SECTOR، ADV_INDUSTRY، ADV_MEDIA)
--   PRT_ADV_USERS / PRIVILEGES / LOGINHISTORY      ← النواة
--
-- الصلاحيات في وحدة ADV:
--   USER    + OWN  : مندوب المبيعات يرى الحسابات وجهات الاتصال كلها، والفرص التي هو مسؤولها أو أنشأها
--   MANAGER + UNIT : رئيس القسم يرى فرص مندوبي وحدته، ويدير القوائم
--   ADMIN   + ALL  : كل شيء
--------------------------------------------------------------------------------


