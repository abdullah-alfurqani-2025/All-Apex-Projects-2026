CREATE OR REPLACE PACKAGE MOINFO_ADV AS

    -- 'Y' إن كان يحق للمستخدم الحالي رؤية الفرصة
    FUNCTION CAN_SEE (p_deal_id IN NUMBER) RETURN VARCHAR2;

    -- 'Y' إن كان للمستخدم الحالي دور MANAGER فأعلى في الوحدة ADV
    FUNCTION IS_MANAGER RETURN VARCHAR2;

    -- يسجّل متابعة على الفرصة، ويحدّث موعد المتابعة القادم، وحالة الفرصة إن أُرسلت
    PROCEDURE ADD_ACTIVITY (
        p_deal_id   IN NUMBER,
        p_note      IN VARCHAR2,
        p_type_id   IN NUMBER DEFAULT NULL,
        p_date      IN DATE   DEFAULT TRUNC(SYSDATE),
        p_next_date IN DATE   DEFAULT NULL,
        p_status_id IN NUMBER DEFAULT NULL
    );

END MOINFO_ADV;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_ADV AS

    FUNCTION CAN_SEE (p_deal_id IN NUMBER) RETURN VARCHAR2 IS
        l_scope      VARCHAR2(10);
        l_owner      NUMBER;
        l_created_by VARCHAR2(255);
        l_unit       NUMBER;
        l_my_emp     NUMBER;
        l_me         VARCHAR2(255) := UPPER(TRIM(V('APP_USER')));
    BEGIN
        l_scope := MOINFO_SEC.DATA_SCOPE('ADV');
        IF l_scope = 'ALL' THEN
            RETURN 'Y';
        ELSIF l_scope IS NULL THEN
            RETURN 'N';
        END IF;

        SELECT d.OWNER_EMPLOYEE_ID, d.CREATED_BY, e.UNIT_ID
          INTO l_owner, l_created_by, l_unit
          FROM MOINFO_ADV_DEALS d
          LEFT JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = d.OWNER_EMPLOYEE_ID
         WHERE d.DEAL_ID = p_deal_id;

        l_my_emp := MOINFO_HR.MY_EMPLOYEE_ID;
        IF (l_my_emp IS NOT NULL AND l_owner = l_my_emp) OR UPPER(l_created_by) = l_me THEN
            RETURN 'Y';
        END IF;
        IF l_scope = 'UNIT' AND l_unit IS NOT NULL THEN
            RETURN MOINFO_SEC.CAN_SEE_UNIT('ADV', l_unit);
        END IF;
        RETURN 'N';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 'N';
    END CAN_SEE;

    FUNCTION IS_MANAGER RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN MOINFO_SEC.HAS_ROLE('ADV', 'MANAGER') THEN 'Y' ELSE 'N' END;
    END IS_MANAGER;

    PROCEDURE ADD_ACTIVITY (
        p_deal_id   IN NUMBER,
        p_note      IN VARCHAR2,
        p_type_id   IN NUMBER DEFAULT NULL,
        p_date      IN DATE   DEFAULT TRUNC(SYSDATE),
        p_next_date IN DATE   DEFAULT NULL,
        p_status_id IN NUMBER DEFAULT NULL
    ) IS
    BEGIN
        IF CAN_SEE(p_deal_id) = 'N' THEN
            RAISE_APPLICATION_ERROR(-20094, 'لا تملك صلاحية على هذه الفرصة');
        END IF;
        IF TRIM(p_note) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20095, 'اكتب نص المتابعة');
        END IF;
        IF p_next_date IS NOT NULL AND p_next_date < TRUNC(NVL(p_date, SYSDATE)) THEN
            RAISE_APPLICATION_ERROR(-20096, 'موعد المتابعة القادم يسبق تاريخ هذه المتابعة');
        END IF;

        INSERT INTO MOINFO_ADV_ACTIVITIES (DEAL_ID, ACTIVITY_TYPE_ID, ACTIVITY_DATE, NOTE_TEXT, NEXT_FOLLOWUP_DATE, STATUS_ID)
        VALUES (p_deal_id, p_type_id, NVL(p_date, TRUNC(SYSDATE)), p_note, p_next_date, p_status_id);

        UPDATE MOINFO_ADV_DEALS
           SET NEXT_FOLLOWUP_DATE = p_next_date,
               STATUS_ID          = NVL(p_status_id, STATUS_ID)
         WHERE DEAL_ID = p_deal_id;
    END ADD_ACTIVITY;

END MOINFO_ADV;
/


