-- 3) Triggers القواعد
--==============================================================================

-- حساب الوكالة لا يكون له وكيل. (التحقق أن الوكيل وكالة يتم في الصفحات بقائمة الوكالات فقط،
-- لأن قراءة الجدول نفسه داخل Trigger السطر تسبب ORA-04091)
CREATE OR REPLACE TRIGGER MOINFO_ADV_ACCOUNTS_RULES_BIU
BEFORE INSERT OR UPDATE OF AGENCY_ID, ACCOUNT_TYPE ON MOINFO_ADV_ACCOUNTS
FOR EACH ROW
BEGIN
    IF :NEW.ACCOUNT_TYPE = 'AGENCY' THEN
        :NEW.AGENCY_ID := NULL;
    END IF;
END;
/

-- الفرصة: المعلن شركة، والوكالة وكالة (افتراضيًا وكيل المعلن)، وجهة الاتصال من المعلن أو الوكالة،
-- والحالة الافتراضية NEW، وتاريخ الإغلاق للحالتين WON و LOST
CREATE OR REPLACE TRIGGER MOINFO_ADV_DEALS_RULES_BIU
BEFORE INSERT OR UPDATE ON MOINFO_ADV_DEALS
FOR EACH ROW
DECLARE
    l_type   MOINFO_ADV_ACCOUNTS.ACCOUNT_TYPE%TYPE;
    l_agency NUMBER;
    l_code   MOINFO_LOOKUPS.LOOKUP_CODE%TYPE;
    l_acc    NUMBER;
    FUNCTION CHANGED (a IN NUMBER, b IN NUMBER) RETURN BOOLEAN IS
    BEGIN
        RETURN NOT ((a = b) OR (a IS NULL AND b IS NULL));
    END;
BEGIN
    -- التحقق فقط عند تغيّر الحقل، حتى لا يقرأ جداول تُحذف منها سطور بالتسلسل (ORA-04091)
    IF (INSERTING OR CHANGED(:NEW.ADVERTISER_ID, :OLD.ADVERTISER_ID)) THEN
        SELECT ACCOUNT_TYPE, AGENCY_ID INTO l_type, l_agency FROM MOINFO_ADV_ACCOUNTS WHERE ACCOUNT_ID = :NEW.ADVERTISER_ID;
        IF l_type <> 'COMPANY' THEN
            RAISE_APPLICATION_ERROR(-20091, 'المعلن يجب أن يكون شركة، لا وكالة');
        END IF;
        IF INSERTING AND :NEW.AGENCY_ID IS NULL THEN
            :NEW.AGENCY_ID := l_agency;
        END IF;
    END IF;

    IF :NEW.AGENCY_ID IS NOT NULL AND (INSERTING OR CHANGED(:NEW.AGENCY_ID, :OLD.AGENCY_ID)) THEN
        SELECT ACCOUNT_TYPE INTO l_type FROM MOINFO_ADV_ACCOUNTS WHERE ACCOUNT_ID = :NEW.AGENCY_ID;
        IF l_type <> 'AGENCY' THEN
            RAISE_APPLICATION_ERROR(-20092, 'الوكالة المختارة ليست وكالة إعلانية');
        END IF;
    END IF;

    IF :NEW.CONTACT_ID IS NOT NULL
       AND ((INSERTING OR CHANGED(:NEW.CONTACT_ID, :OLD.CONTACT_ID)) OR (INSERTING OR CHANGED(:NEW.ADVERTISER_ID, :OLD.ADVERTISER_ID))
            OR (INSERTING OR CHANGED(:NEW.AGENCY_ID, :OLD.AGENCY_ID))) THEN
        SELECT ACCOUNT_ID INTO l_acc FROM MOINFO_ADV_CONTACTS WHERE CONTACT_ID = :NEW.CONTACT_ID;
        IF l_acc <> :NEW.ADVERTISER_ID AND (:NEW.AGENCY_ID IS NULL OR l_acc <> :NEW.AGENCY_ID) THEN
            RAISE_APPLICATION_ERROR(-20093, 'جهة الاتصال لا تتبع المعلن ولا الوكالة');
        END IF;
    END IF;

    IF :NEW.STATUS_ID IS NULL THEN
        SELECT LOOKUP_ID INTO :NEW.STATUS_ID
          FROM MOINFO_LOOKUPS
         WHERE LOOKUP_TYPE = 'ADV_DEAL_STATUS' AND LOOKUP_CODE = 'NEW';
    END IF;
    SELECT LOOKUP_CODE INTO l_code FROM MOINFO_LOOKUPS WHERE LOOKUP_ID = :NEW.STATUS_ID;
    IF l_code IN ('WON', 'LOST') THEN
        IF :NEW.CLOSED_DATE IS NULL THEN
            :NEW.CLOSED_DATE := TRUNC(SYSDATE);
        END IF;
        :NEW.NEXT_FOLLOWUP_DATE := NULL;
    ELSE
        :NEW.CLOSED_DATE := NULL;
    END IF;
END;
/


