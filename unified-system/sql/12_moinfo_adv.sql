CREATE TABLE MOINFO_ADV_ACCOUNTS (
    ACCOUNT_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ACCOUNT_TYPE    VARCHAR2(10) DEFAULT ON NULL 'COMPANY' NOT NULL,
    NAME            VARCHAR2(500 CHAR)          NOT NULL,
    AGENCY_ID       NUMBER,
    SECTOR_ID       NUMBER,
    INDUSTRY_ID     NUMBER,
    PHONE           VARCHAR2(30),
    EMAIL           VARCHAR2(255),
    WEBSITE         VARCHAR2(255),
    ADDRESS         VARCHAR2(500 CHAR),
    NOTES           VARCHAR2(1000 CHAR),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_ADV_ACC_PK PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT MOINFO_ADV_ACC_AGENCY_FK FOREIGN KEY (AGENCY_ID) REFERENCES MOINFO_ADV_ACCOUNTS (ACCOUNT_ID),
    CONSTRAINT MOINFO_ADV_ACC_SECTOR_FK FOREIGN KEY (SECTOR_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
