       st.LOOKUP_CODE AS STATUS_CODE,
       st.NAME_AR AS STATUS_AR,
       CASE WHEN st.LOOKUP_CODE IN ('WON', 'LOST') THEN 'Y' ELSE 'N' END AS IS_CLOSED,
       d.OWNER_EMPLOYEE_ID,
       e.NAME_AR AS OWNER_AR,
       e.UNIT_ID AS OWNER_UNIT_ID,
       d.DEAL_DATE,
       d.EXPECTED_AMOUNT,
       d.NEXT_FOLLOWUP_DATE,
       CASE
           WHEN st.LOOKUP_CODE IN ('WON', 'LOST') OR d.NEXT_FOLLOWUP_DATE IS NULL THEN NULL
           WHEN d.NEXT_FOLLOWUP_DATE < TRUNC(SYSDATE) THEN 'متأخرة'
           WHEN d.NEXT_FOLLOWUP_DATE = TRUNC(SYSDATE) THEN 'اليوم'
       END AS FOLLOWUP_STATE_AR,
       d.CLOSED_DATE,
       d.SALES_HISTORY,
       d.OBJECTIONS,
       d.NOTES,
       d.IS_ACTIVE,
       (SELECT COUNT(*) FROM MOINFO_ADV_ACTIVITIES x WHERE x.DEAL_ID = d.DEAL_ID) AS ACTIVITIES_COUNT,
       d.CREATED_BY,
       d.CREATED_AT
  FROM MOINFO_ADV_DEALS d
  JOIN MOINFO_ADV_ACCOUNTS a       ON a.ACCOUNT_ID = d.ADVERTISER_ID
  JOIN MOINFO_LOOKUPS st           ON st.LOOKUP_ID = d.STATUS_ID
  LEFT JOIN MOINFO_ADV_ACCOUNTS ag ON ag.ACCOUNT_ID = d.AGENCY_ID
  LEFT JOIN MOINFO_ADV_CONTACTS c  ON c.CONTACT_ID = d.CONTACT_ID
  LEFT JOIN MOINFO_LOOKUPS m       ON m.LOOKUP_ID = d.MEDIA_ID
  LEFT JOIN MOINFO_EMPLOYEES e     ON e.EMPLOYEE_ID = d.OWNER_EMPLOYEE_ID;

CREATE OR REPLACE VIEW MOINFO_ADV_V_ACTIVITIES AS
SELECT x.ACTIVITY_ID,
       x.DEAL_ID,
       x.ACTIVITY_DATE,
       x.ACTIVITY_TYPE_ID,
       t.NAME_AR AS ACTIVITY_TYPE_AR,
       x.NOTE_TEXT,
       x.NEXT_FOLLOWUP_DATE,
       x.STATUS_ID,
       st.NAME_AR AS STATUS_AR,
       x.CREATED_BY,
       NVL(u.DISPLAY_NAME, x.CREATED_BY) AS CREATED_BY_NAME,
       x.CREATED_AT
  FROM MOINFO_ADV_ACTIVITIES x
  LEFT JOIN MOINFO_LOOKUPS t  ON t.LOOKUP_ID = x.ACTIVITY_TYPE_ID
  LEFT JOIN MOINFO_LOOKUPS st ON st.LOOKUP_ID = x.STATUS_ID
  LEFT JOIN MOINFO_USERS u    ON u.USERNAME = x.CREATED_BY;

-- إحصائيات الفرص حسب الشهر والوسيلة والحالة والمندوب
CREATE OR REPLACE VIEW MOINFO_ADV_V_STATS AS
SELECT TRUNC(d.DEAL_DATE, 'MM') AS DEAL_MONTH,
       d.MEDIA_AR,
       d.STATUS_CODE,
       d.STATUS_AR,
       d.OWNER_EMPLOYEE_ID,
       d.OWNER_AR,
       d.OWNER_UNIT_ID,
       COUNT(*) AS DEALS_COUNT,
       SUM(d.EXPECTED_AMOUNT) AS EXPECTED_AMOUNT
  FROM MOINFO_ADV_V_DEALS d
 WHERE d.IS_ACTIVE = 'Y'
 GROUP BY TRUNC(d.DEAL_DATE, 'MM'), d.MEDIA_AR, d.STATUS_CODE, d.STATUS_AR, d.OWNER_EMPLOYEE_ID, d.OWNER_AR, d.OWNER_UNIT_ID;


