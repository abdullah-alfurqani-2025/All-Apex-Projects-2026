CREATE OR REPLACE VIEW MOINFO_ADV_V_ACCOUNTS AS
SELECT a.ACCOUNT_ID,
       a.ACCOUNT_TYPE,
       CASE a.ACCOUNT_TYPE WHEN 'AGENCY' THEN 'وكالة' ELSE 'شركة' END AS ACCOUNT_TYPE_AR,
       a.NAME,
       a.AGENCY_ID,
       ag.NAME AS AGENCY_NAME,
       a.SECTOR_ID,
       s.NAME_AR AS SECTOR_AR,
       a.INDUSTRY_ID,
       i.NAME_AR AS INDUSTRY_AR,
       a.PHONE,
       a.EMAIL,
       a.WEBSITE,
       a.ADDRESS,
       a.NOTES,
       a.IS_ACTIVE,
       (SELECT COUNT(*) FROM MOINFO_ADV_CONTACTS c WHERE c.ACCOUNT_ID = a.ACCOUNT_ID AND c.IS_ACTIVE = 'Y') AS CONTACTS_COUNT,
       (SELECT COUNT(*) FROM MOINFO_ADV_ACCOUNTS x WHERE x.AGENCY_ID = a.ACCOUNT_ID) AS CLIENTS_COUNT,
       (SELECT c.NAME || NVL2(c.MOBILE, ' - ' || c.MOBILE, '')
          FROM MOINFO_ADV_CONTACTS c
         WHERE c.ACCOUNT_ID = a.ACCOUNT_ID AND c.IS_ACTIVE = 'Y'
         ORDER BY CASE c.IS_PRIMARY WHEN 'Y' THEN 0 ELSE 1 END, c.CONTACT_ID
         FETCH FIRST 1 ROW ONLY) AS PRIMARY_CONTACT
  FROM MOINFO_ADV_ACCOUNTS a
  LEFT JOIN MOINFO_ADV_ACCOUNTS ag ON ag.ACCOUNT_ID = a.AGENCY_ID
  LEFT JOIN MOINFO_LOOKUPS s       ON s.LOOKUP_ID = a.SECTOR_ID
  LEFT JOIN MOINFO_LOOKUPS i       ON i.LOOKUP_ID = a.INDUSTRY_ID;

