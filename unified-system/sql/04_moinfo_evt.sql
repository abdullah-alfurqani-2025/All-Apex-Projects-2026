CREATE TABLE MOINFO_EVT_EVENTS (
    EVENT_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EMPLOYEE_ID     NUMBER                      NOT NULL,
    EVENT_TYPE_ID   NUMBER                      NOT NULL,
    TITLE           VARCHAR2(500 CHAR)          NOT NULL,
    PLACE           VARCHAR2(200 CHAR),
    COUNTRY_ID      NUMBER,
    START_DATE      DATE                        NOT NULL,
    END_DATE        DATE                        NOT NULL,
    LETTER_NO       VARCHAR2(50 CHAR),
    LETTER_DATE     DATE,
    COMMENTS        VARCHAR2(1000 CHAR),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_EVT_EVENTS_PK PRIMARY KEY (EVENT_ID),
    CONSTRAINT MOINFO_EVT_EVENTS_EMP_FK FOREIGN KEY (EMPLOYEE_ID) REFERENCES MOINFO_EMPLOYEES (EMPLOYEE_ID),
    CONSTRAINT MOINFO_EVT_EVENTS_TYPE_FK FOREIGN KEY (EVENT_TYPE_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_EVT_EVENTS_COUNTRY_FK FOREIGN KEY (COUNTRY_ID) REFERENCES MOINFO_COUNTRIES (COUNTRY_ID),
    CONSTRAINT MOINFO_EVT_EVENTS_DATES_CK CHECK (END_DATE >= START_DATE),
    CONSTRAINT MOINFO_EVT_EVENTS_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_EVT_EVENTS_EMP_IX     ON MOINFO_EVT_EVENTS (EMPLOYEE_ID, START_DATE);
CREATE INDEX MOINFO_EVT_EVENTS_TYPE_IX    ON MOINFO_EVT_EVENTS (EVENT_TYPE_ID);
CREATE INDEX MOINFO_EVT_EVENTS_COUNTRY_IX ON MOINFO_EVT_EVENTS (COUNTRY_ID);
CREATE INDEX MOINFO_EVT_EVENTS_DATE_IX    ON MOINFO_EVT_EVENTS (START_DATE);

