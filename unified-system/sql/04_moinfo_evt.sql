CREATE OR REPLACE PACKAGE MOINFO_EVT AS

    -- 'Y' إن كان يحق للمستخدم الحالي رؤية مشاركات هذا الموظف
    -- مثال: WHERE MOINFO_EVT.CAN_SEE(EMPLOYEE_ID) = 'Y'
    FUNCTION CAN_SEE (p_employee_id IN NUMBER) RETURN VARCHAR2;

    -- 'Y' إن تداخلت الفترة مع مشاركة أخرى للموظف نفسه
    FUNCTION HAS_OVERLAP (
        p_employee_id IN NUMBER,
        p_start_date  IN DATE,
        p_end_date    IN DATE,
        p_event_id    IN NUMBER DEFAULT NULL
    ) RETURN VARCHAR2;

    -- نص يصف المشاركات المتداخلة، أو NULL إن لم يوجد تداخل.
    -- يصلح لـ Validation من نوع Function Body Returning Error Text:
    --   RETURN MOINFO_EVT.OVERLAP_MESSAGE(:P2002_EMPLOYEE_ID, :P2002_START_DATE, :P2002_END_DATE, :P2002_EVENT_ID);
    FUNCTION OVERLAP_MESSAGE (
        p_employee_id IN NUMBER,
        p_start_date  IN DATE,
        p_end_date    IN DATE,
        p_event_id    IN NUMBER DEFAULT NULL
    ) RETURN VARCHAR2;

END MOINFO_EVT;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_EVT AS

    FUNCTION CAN_SEE (p_employee_id IN NUMBER) RETURN VARCHAR2 IS
        l_scope   VARCHAR2(10);
        l_unit_id NUMBER;
    BEGIN
        IF p_employee_id IS NULL THEN
            RETURN 'N';
        END IF;

        l_scope := MOINFO_SEC.DATA_SCOPE('EVT');

        IF l_scope = 'ALL' THEN
            RETURN 'Y';
        ELSIF l_scope IS NULL THEN
            RETURN 'N';
        END IF;

        -- مشاركات الموظف نفسه مرئية له في كل النطاقات
        IF p_employee_id = MOINFO_HR.MY_EMPLOYEE_ID THEN
            RETURN 'Y';
        END IF;

        IF l_scope = 'UNIT' THEN
            SELECT UNIT_ID INTO l_unit_id FROM MOINFO_EMPLOYEES WHERE EMPLOYEE_ID = p_employee_id;
            RETURN MOINFO_SEC.CAN_SEE_UNIT('EVT', l_unit_id);
        END IF;

        RETURN 'N';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 'N';
    END CAN_SEE;

    FUNCTION HAS_OVERLAP (
        p_employee_id IN NUMBER,
        p_start_date  IN DATE,
        p_end_date    IN DATE,
        p_event_id    IN NUMBER DEFAULT NULL
    ) RETURN VARCHAR2 IS
        l_n NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO l_n
          FROM MOINFO_EVT_EVENTS
         WHERE EMPLOYEE_ID = p_employee_id
           AND IS_ACTIVE = 'Y'
           AND EVENT_ID <> NVL(p_event_id, -1)
           AND START_DATE <= p_end_date
           AND END_DATE   >= p_start_date;
        RETURN CASE WHEN l_n > 0 THEN 'Y' ELSE 'N' END;
    END HAS_OVERLAP;

    FUNCTION OVERLAP_MESSAGE (
        p_employee_id IN NUMBER,
        p_start_date  IN DATE,
        p_end_date    IN DATE,
        p_event_id    IN NUMBER DEFAULT NULL
    ) RETURN VARCHAR2 IS
        l_msg VARCHAR2(4000);
    BEGIN
        FOR r IN (SELECT TITLE, START_DATE, END_DATE
                    FROM MOINFO_EVT_EVENTS
                   WHERE EMPLOYEE_ID = p_employee_id
                     AND IS_ACTIVE = 'Y'
                     AND EVENT_ID <> NVL(p_event_id, -1)
                     AND START_DATE <= p_end_date
                     AND END_DATE   >= p_start_date
                   ORDER BY START_DATE
                   FETCH FIRST 5 ROWS ONLY)
        LOOP
            l_msg := l_msg
                  || CASE WHEN l_msg IS NOT NULL THEN '، ' END
                  || r.TITLE || ' (' || TO_CHAR(r.START_DATE, 'DD/MM/YYYY')
                  || ' - ' || TO_CHAR(r.END_DATE, 'DD/MM/YYYY') || ')';
        END LOOP;

        IF l_msg IS NULL THEN
            RETURN NULL;
        END IF;
        RETURN SUBSTR('الفترة تتداخل مع مشاركة أخرى للموظف: ' || l_msg, 1, 4000);
    END OVERLAP_MESSAGE;

END MOINFO_EVT;
/


