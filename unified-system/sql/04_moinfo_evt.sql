-- المشاركات مع بيانات الموظف ووحدته
-- مثال في الصفحة: SELECT * FROM MOINFO_EVT_V_EVENTS WHERE MOINFO_EVT.CAN_SEE(EMPLOYEE_ID) = 'Y'
CREATE OR REPLACE VIEW MOINFO_EVT_V_EVENTS AS
SELECT ev.EVENT_ID,
       ev.EMPLOYEE_ID,
       e.EMPLOYEE_NO,
       e.NAME_AR AS EMPLOYEE_NAME_AR,
       e.UNIT_ID,
       u.UNIT_NAME_AR,
       u.UNIT_PATH_AR,
       t.TITLE_NAME_AR,
       ev.EVENT_TYPE_ID,
       typ.NAME_AR AS EVENT_TYPE_AR,
       ev.TITLE,
       ev.PLACE,
       ev.COUNTRY_ID,
       c.NAME_AR AS COUNTRY_AR,
       ev.START_DATE,
       ev.END_DATE,
       ev.END_DATE - ev.START_DATE + 1 AS DURATION_DAYS,
       EXTRACT(YEAR FROM ev.START_DATE) AS EVENT_YEAR,
       ev.LETTER_NO,
       ev.LETTER_DATE,
       ev.COMMENTS,
       ev.IS_ACTIVE,
       ev.CREATED_BY,
       ev.CREATED_AT
  FROM MOINFO_EVT_EVENTS ev
  JOIN MOINFO_EMPLOYEES e        ON e.EMPLOYEE_ID = ev.EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS u     ON u.UNIT_ID = e.UNIT_ID
  LEFT JOIN MOINFO_TITLES t      ON t.TITLE_ID = e.TITLE_ID
  LEFT JOIN MOINFO_LOOKUPS typ   ON typ.LOOKUP_ID = ev.EVENT_TYPE_ID
  LEFT JOIN MOINFO_COUNTRIES c   ON c.COUNTRY_ID = ev.COUNTRY_ID;

-- المشاركات المتداخلة لنفس الموظف (بديل صفحة Overlap Events): كل زوج متداخل في سطر
CREATE OR REPLACE VIEW MOINFO_EVT_V_OVERLAPS AS
SELECT a.EMPLOYEE_ID,
       e.EMPLOYEE_NO,
       e.NAME_AR AS EMPLOYEE_NAME_AR,
       e.UNIT_ID,
       a.EVENT_ID   AS EVENT_ID_1,
       a.TITLE      AS TITLE_1,
       a.START_DATE AS START_DATE_1,
       a.END_DATE   AS END_DATE_1,
       b.EVENT_ID   AS EVENT_ID_2,
       b.TITLE      AS TITLE_2,
       b.START_DATE AS START_DATE_2,
       b.END_DATE   AS END_DATE_2,
       LEAST(a.END_DATE, b.END_DATE) - GREATEST(a.START_DATE, b.START_DATE) + 1 AS OVERLAP_DAYS
  FROM MOINFO_EVT_EVENTS a
  JOIN MOINFO_EVT_EVENTS b
    ON b.EMPLOYEE_ID = a.EMPLOYEE_ID
   AND b.EVENT_ID > a.EVENT_ID
   AND b.START_DATE <= a.END_DATE
   AND b.END_DATE   >= a.START_DATE
  JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = a.EMPLOYEE_ID
 WHERE a.IS_ACTIVE = 'Y'
   AND b.IS_ACTIVE = 'Y';

-- ملخص سنوي لكل موظف: عدد المشاركات وإجمالي الأيام (بديل Events by Employee)
CREATE OR REPLACE VIEW MOINFO_EVT_V_EMPLOYEE_SUMMARY AS
SELECT ev.EMPLOYEE_ID,
       e.EMPLOYEE_NO,
       e.NAME_AR AS EMPLOYEE_NAME_AR,
       e.UNIT_ID,
       u.UNIT_PATH_AR,
       EXTRACT(YEAR FROM ev.START_DATE) AS EVENT_YEAR,
       COUNT(*) AS EVENTS_COUNT,
       SUM(ev.END_DATE - ev.START_DATE + 1) AS TOTAL_DAYS
  FROM MOINFO_EVT_EVENTS ev
  JOIN MOINFO_EMPLOYEES e    ON e.EMPLOYEE_ID = ev.EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS u ON u.UNIT_ID = e.UNIT_ID
 WHERE ev.IS_ACTIVE = 'Y'
 GROUP BY ev.EMPLOYEE_ID, e.EMPLOYEE_NO, e.NAME_AR, e.UNIT_ID, u.UNIT_PATH_AR, EXTRACT(YEAR FROM ev.START_DATE);


