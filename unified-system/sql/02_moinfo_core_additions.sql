--==============================================================================
-- 3) MOINFO_ADMIN: إدارة المستخدمين وصلاحياتهم
--   تُستدعى من صفحات الإدارة في APEX، والصلاحية عليها تُضبط بـ Authorization Scheme.
--==============================================================================
CREATE OR REPLACE PACKAGE MOINFO_ADMIN AS

    -- ينشئ حسابًا بكلمة مرور مؤقتة يُطلب تغييرها عند أول دخول، ويُرجع USER_ID
    FUNCTION CREATE_USER (
        p_username      IN VARCHAR2,
        p_display_name  IN VARCHAR2,
        p_temp_password IN VARCHAR2,
        p_employee_id   IN NUMBER   DEFAULT NULL,
        p_email         IN VARCHAR2 DEFAULT NULL,
        p_home_module   IN VARCHAR2 DEFAULT NULL
    ) RETURN NUMBER;

    -- يمنح المستخدم وحدة بدور ونطاق بيانات، أو يحدّثهما إن كانت ممنوحة مسبقًا
    PROCEDURE GRANT_MODULE (
        p_user_id       IN NUMBER,
        p_module_code   IN VARCHAR2,
        p_role_code     IN VARCHAR2,
        p_data_scope    IN VARCHAR2 DEFAULT 'UNIT',
        p_scope_unit_id IN NUMBER   DEFAULT NULL
    );

    PROCEDURE REVOKE_MODULE (p_user_id IN NUMBER, p_module_code IN VARCHAR2);

    PROCEDURE RESET_PASSWORD (p_user_id IN NUMBER, p_temp_password IN VARCHAR2);

    PROCEDURE UNLOCK_USER (p_user_id IN NUMBER);

END MOINFO_ADMIN;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_ADMIN AS

    FUNCTION CREATE_USER (
        p_username      IN VARCHAR2,
        p_display_name  IN VARCHAR2,
        p_temp_password IN VARCHAR2,
        p_employee_id   IN NUMBER   DEFAULT NULL,
        p_email         IN VARCHAR2 DEFAULT NULL,
        p_home_module   IN VARCHAR2 DEFAULT NULL
    ) RETURN NUMBER IS
        l_user_id  MOINFO_USERS.USER_ID%TYPE;
        l_username MOINFO_USERS.USERNAME%TYPE := UPPER(TRIM(p_username));
    BEGIN
        INSERT INTO MOINFO_USERS (USERNAME, DISPLAY_NAME, EMPLOYEE_ID, EMAIL, HOME_MODULE)
        VALUES (l_username, p_display_name, p_employee_id, p_email, UPPER(p_home_module))
        RETURNING USER_ID INTO l_user_id;

        MOINFO_AUTH.SET_PASSWORD(l_user_id, p_temp_password, 'Y');
        RETURN l_user_id;
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20020, 'اسم المستخدم أو الموظف مرتبط بحساب آخر مسبقًا');
    END CREATE_USER;

    PROCEDURE GRANT_MODULE (
        p_user_id       IN NUMBER,
        p_module_code   IN VARCHAR2,
        p_role_code     IN VARCHAR2,
        p_data_scope    IN VARCHAR2 DEFAULT 'UNIT',
        p_scope_unit_id IN NUMBER   DEFAULT NULL
    ) IS
        l_module  MOINFO_MODULES.MODULE_CODE%TYPE := UPPER(p_module_code);
        l_role_id MOINFO_ROLES.ROLE_ID%TYPE;
        l_scope   VARCHAR2(10) := UPPER(NVL(p_data_scope, 'UNIT'));
    BEGIN
        -- الدور الخاص بالوحدة له الأولوية على الدور العام بنفس الرمز
        BEGIN
            SELECT ROLE_ID
              INTO l_role_id
              FROM (SELECT ROLE_ID
                      FROM MOINFO_ROLES
                     WHERE ROLE_CODE = UPPER(p_role_code)
                       AND (MODULE_CODE = l_module OR MODULE_CODE IS NULL)
                       AND IS_ACTIVE = 'Y'
                     ORDER BY CASE WHEN MODULE_CODE IS NULL THEN 1 ELSE 0 END)
             WHERE ROWNUM = 1;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20021, 'الدور غير موجود: ' || p_role_code);
        END;

        MERGE INTO MOINFO_USER_MODULES um
        USING (SELECT p_user_id AS USER_ID, l_module AS MODULE_CODE FROM DUAL) s
           ON (um.USER_ID = s.USER_ID AND um.MODULE_CODE = s.MODULE_CODE)
         WHEN MATCHED THEN UPDATE
              SET um.ROLE_ID       = l_role_id,
                  um.DATA_SCOPE    = l_scope,
                  um.SCOPE_UNIT_ID = p_scope_unit_id,
                  um.IS_ACTIVE     = 'Y'
         WHEN NOT MATCHED THEN INSERT
              (USER_ID, MODULE_CODE, ROLE_ID, DATA_SCOPE, SCOPE_UNIT_ID)
              VALUES (s.USER_ID, s.MODULE_CODE, l_role_id, l_scope, p_scope_unit_id);
    END GRANT_MODULE;

    PROCEDURE REVOKE_MODULE (p_user_id IN NUMBER, p_module_code IN VARCHAR2) IS
    BEGIN
        DELETE FROM MOINFO_USER_MODULES
         WHERE USER_ID = p_user_id
           AND MODULE_CODE = UPPER(p_module_code);
    END REVOKE_MODULE;

    PROCEDURE RESET_PASSWORD (p_user_id IN NUMBER, p_temp_password IN VARCHAR2) IS
    BEGIN
        MOINFO_AUTH.SET_PASSWORD(p_user_id, p_temp_password, 'Y');
    END RESET_PASSWORD;

    PROCEDURE UNLOCK_USER (p_user_id IN NUMBER) IS
    BEGIN
        UPDATE MOINFO_USER_CREDENTIALS
           SET FAILED_LOGINS = 0,
               LOCKED_UNTIL  = NULL
         WHERE USER_ID = p_user_id;
    END UNLOCK_USER;

END MOINFO_ADMIN;
