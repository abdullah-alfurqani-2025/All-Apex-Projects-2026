--==============================================================================
-- 1) القوائم المرجعية
--   بدل إنشاء جدول صغير لكل قائمة (الحالة الاجتماعية، المؤهل، البنك ...)
--   تُجمع القوائم البسيطة في جدول واحد مصنّف بالنوع.
--==============================================================================
CREATE TABLE MOINFO_LOOKUP_TYPES (
    LOOKUP_TYPE     VARCHAR2(50)                NOT NULL,
    MODULE_CODE     VARCHAR2(10)                NOT NULL,
    TYPE_NAME_AR    VARCHAR2(150 CHAR)          NOT NULL,
    TYPE_NAME_EN    VARCHAR2(150 CHAR),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_LOOKUP_TYPES_PK PRIMARY KEY (LOOKUP_TYPE),
    CONSTRAINT MOINFO_LOOKUP_TYPES_MOD_FK FOREIGN KEY (MODULE_CODE) REFERENCES MOINFO_MODULES (MODULE_CODE),
    CONSTRAINT MOINFO_LOOKUP_TYPES_CODE_CK CHECK (LOOKUP_TYPE = UPPER(LOOKUP_TYPE)),
    CONSTRAINT MOINFO_LOOKUP_TYPES_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_LOOKUP_TYPES_MOD_IX ON MOINFO_LOOKUP_TYPES (MODULE_CODE);

CREATE TABLE MOINFO_LOOKUPS (
    LOOKUP_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    LOOKUP_TYPE     VARCHAR2(50)                NOT NULL,
    LOOKUP_CODE     VARCHAR2(50),
    NAME_AR         VARCHAR2(255 CHAR)          NOT NULL,
    NAME_EN         VARCHAR2(255 CHAR),
    SORT_ORDER      NUMBER(6),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_LOOKUPS_PK PRIMARY KEY (LOOKUP_ID),
    CONSTRAINT MOINFO_LOOKUPS_CODE_UK UNIQUE (LOOKUP_TYPE, LOOKUP_CODE),
    CONSTRAINT MOINFO_LOOKUPS_TYPE_FK FOREIGN KEY (LOOKUP_TYPE) REFERENCES MOINFO_LOOKUP_TYPES (LOOKUP_TYPE),
    CONSTRAINT MOINFO_LOOKUPS_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_LOOKUPS_TYPE_IX ON MOINFO_LOOKUPS (LOOKUP_TYPE, SORT_ORDER);


