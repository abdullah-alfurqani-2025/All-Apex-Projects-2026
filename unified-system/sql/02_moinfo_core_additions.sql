--==============================================================================
-- نسخة محدّثة من جسم MOINFO_UTIL: تقرأ AUDIT_EXCLUDE_TABLES
--==============================================================================
CREATE OR REPLACE PACKAGE BODY MOINFO_UTIL AS

    -- جداول لا تُنشأ لها Triggers
    FUNCTION is_excluded (p_table IN VARCHAR2) RETURN BOOLEAN IS
    BEGIN
        RETURN p_table IN ('MOINFO_AUDIT_LOG', 'MOINFO_LOGIN_HISTORY', 'MOINFO_USER_CREDENTIALS');
    END is_excluded;

    -- جداول تُنشأ لها Triggers بلا تدقيق (مثل السجلات كثيفة الإدخال).
    -- تُحدَّد في الإعداد AUDIT_EXCLUDE_TABLES مفصولة بفواصل.
    FUNCTION audit_disabled (p_table IN VARCHAR2) RETURN BOOLEAN IS
        l_list VARCHAR2(4000) := ',' || UPPER(REPLACE(GET_SETTING('AUDIT_EXCLUDE_TABLES'), ' ', '')) || ',';
    BEGIN
        RETURN INSTR(l_list, ',' || UPPER(p_table) || ',') > 0;
    END audit_disabled;

    FUNCTION APP_USER_NAME RETURN VARCHAR2 IS
    BEGIN
        RETURN COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), SYS_CONTEXT('USERENV', 'SESSION_USER'));
    END APP_USER_NAME;

    FUNCTION GET_SETTING (p_key IN VARCHAR2, p_default IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
        l_value MOINFO_SETTINGS.SETTING_VALUE%TYPE;
    BEGIN
        SELECT SETTING_VALUE INTO l_value FROM MOINFO_SETTINGS WHERE SETTING_KEY = p_key;
        RETURN NVL(l_value, p_default);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN p_default;
    END GET_SETTING;

    PROCEDURE LOG_AUDIT (
        p_table_name IN VARCHAR2,
        p_row_pk     IN VARCHAR2,
        p_action     IN VARCHAR2,
        p_old_data   IN CLOB,
        p_new_data   IN CLOB
    ) IS
    BEGIN
        INSERT INTO MOINFO_AUDIT_LOG (TABLE_NAME, ROW_PK, ACTION, CHANGED_BY, CHANGED_AT, OLD_DATA, NEW_DATA)
        VALUES (p_table_name, SUBSTR(p_row_pk, 1, 400), p_action, APP_USER_NAME, SYSTIMESTAMP, p_old_data, p_new_data);
    END LOG_AUDIT;

    PROCEDURE CREATE_TABLE_TRIGGER (p_table_name IN VARCHAR2, p_audit IN VARCHAR2 DEFAULT 'Y') IS
        l_tab         VARCHAR2(128) := UPPER(TRIM(p_table_name));
        l_trg         VARCHAR2(128);
        l_pk_new      VARCHAR2(4000);
        l_pk_old      VARCHAR2(4000);
        l_json_new    CLOB;
        l_json_old    CLOB;
        l_body        CLOB;
        l_has_created BOOLEAN;
        l_has_updated BOOLEAN;
        l_count       NUMBER;
        l_lf          CONSTANT VARCHAR2(1) := CHR(10);

        FUNCTION has_col (p_col IN VARCHAR2) RETURN BOOLEAN IS
            l_n NUMBER;
        BEGIN
            SELECT COUNT(*) INTO l_n
              FROM USER_TAB_COLUMNS
             WHERE TABLE_NAME = l_tab
               AND COLUMN_NAME = p_col;
            RETURN l_n > 0;
        END has_col;
    BEGIN
        SELECT COUNT(*) INTO l_count FROM USER_TABLES WHERE TABLE_NAME = l_tab;
        IF l_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20010, 'الجدول غير موجود: ' || l_tab);
        END IF;

        l_trg := SUBSTR(l_tab, 1, 123) || '_BIUD';
        l_has_created := has_col('CREATED_BY') AND has_col('CREATED_AT');
        l_has_updated := has_col('UPDATED_BY') AND has_col('UPDATED_AT');

        -- المفتاح الأساسي (يدعم المفاتيح المركبة)
        FOR r IN (SELECT cc.COLUMN_NAME
                    FROM USER_CONSTRAINTS c
                    JOIN USER_CONS_COLUMNS cc ON cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
                   WHERE c.TABLE_NAME = l_tab
                     AND c.CONSTRAINT_TYPE = 'P'
                   ORDER BY cc.POSITION)
        LOOP
            IF l_pk_new IS NOT NULL THEN
                l_pk_new := l_pk_new || q'[ || '|' || ]';
                l_pk_old := l_pk_old || q'[ || '|' || ]';
            END IF;
            l_pk_new := l_pk_new || 'TO_CHAR(:NEW."' || r.COLUMN_NAME || '")';
            l_pk_old := l_pk_old || 'TO_CHAR(:OLD."' || r.COLUMN_NAME || '")';
        END LOOP;

        IF l_pk_new IS NULL THEN
            RAISE_APPLICATION_ERROR(-20011, 'الجدول بلا مفتاح أساسي: ' || l_tab);
        END IF;

        -- أعمدة الـ JSON (بدون الملفات وأعمدة الإنشاء والتعديل)
        -- التواريخ تُحوَّل إلى نص بصيغة ثابتة حتى لا تتأثر بإعدادات NLS
        FOR r IN (SELECT COLUMN_NAME,
                         CASE
                             WHEN DATA_TYPE = 'DATE'
                                 THEN q'[TO_CHAR(#, 'YYYY-MM-DD HH24:MI:SS')]'
                             WHEN DATA_TYPE LIKE 'TIMESTAMP%'
                                 THEN q'[TO_CHAR(#, 'YYYY-MM-DD HH24:MI:SS.FF3')]'
                             ELSE '#'
                         END AS EXPR
                    FROM USER_TAB_COLUMNS
                   WHERE TABLE_NAME = l_tab
                     AND DATA_TYPE NOT IN ('BLOB', 'BFILE', 'LONG', 'LONG RAW', 'RAW')
                     AND COLUMN_NAME NOT IN ('CREATED_BY', 'CREATED_AT', 'UPDATED_BY', 'UPDATED_AT')
                   ORDER BY COLUMN_ID)
        LOOP
            IF l_json_new IS NOT NULL THEN
                l_json_new := l_json_new || ', ';
                l_json_old := l_json_old || ', ';
            END IF;
            l_json_new := l_json_new || '''' || r.COLUMN_NAME || ''' VALUE '
                       || REPLACE(r.EXPR, '#', ':NEW."' || r.COLUMN_NAME || '"');
            l_json_old := l_json_old || '''' || r.COLUMN_NAME || ''' VALUE '
                       || REPLACE(r.EXPR, '#', ':OLD."' || r.COLUMN_NAME || '"');
        END LOOP;

        l_body := 'CREATE OR REPLACE TRIGGER "' || l_trg || '"' || l_lf
               || 'BEFORE INSERT OR UPDATE OR DELETE ON "' || l_tab || '"' || l_lf
               || 'FOR EACH ROW' || l_lf
               || 'DECLARE' || l_lf
               || '    l_user VARCHAR2(255) := MOINFO_UTIL.APP_USER_NAME;' || l_lf
               || '    l_old  CLOB;' || l_lf
               || '    l_new  CLOB;' || l_lf
               || 'BEGIN' || l_lf
               || '    NULL;' || l_lf;

        IF l_has_created THEN
            l_body := l_body
               || '    IF INSERTING THEN' || l_lf
               || '        :NEW.CREATED_BY := l_user;' || l_lf
               || '        :NEW.CREATED_AT := SYSTIMESTAMP;' || l_lf
               || '    ELSIF UPDATING THEN' || l_lf
               || '        :NEW.CREATED_BY := :OLD.CREATED_BY;' || l_lf
               || '        :NEW.CREATED_AT := :OLD.CREATED_AT;' || l_lf
               || '    END IF;' || l_lf;
        END IF;

        IF l_has_updated THEN
            l_body := l_body
               || '    IF INSERTING OR UPDATING THEN' || l_lf
               || '        :NEW.UPDATED_BY := l_user;' || l_lf
               || '        :NEW.UPDATED_AT := SYSTIMESTAMP;' || l_lf
               || '    END IF;' || l_lf;
        END IF;

        IF NVL(p_audit, 'Y') = 'Y' AND l_json_new IS NOT NULL THEN
            l_body := l_body
               || '    IF INSERTING OR UPDATING THEN' || l_lf
               || '        SELECT JSON_OBJECT(' || l_json_new || ' RETURNING CLOB) INTO l_new FROM DUAL;' || l_lf
               || '    END IF;' || l_lf
               || '    IF UPDATING OR DELETING THEN' || l_lf
               || '        SELECT JSON_OBJECT(' || l_json_old || ' RETURNING CLOB) INTO l_old FROM DUAL;' || l_lf
               || '    END IF;' || l_lf
               -- لا يُسجَّل التعديل إن لم تتغير أي قيمة فعلية
               || '    IF NOT (UPDATING AND DBMS_LOB.COMPARE(l_old, l_new) = 0) THEN' || l_lf
               || '        MOINFO_UTIL.LOG_AUDIT(' || l_lf
               || '            p_table_name => ''' || l_tab || ''',' || l_lf
               || '            p_row_pk     => CASE WHEN DELETING THEN ' || l_pk_old || ' ELSE ' || l_pk_new || ' END,' || l_lf
               || '            p_action     => CASE WHEN INSERTING THEN ''I'' WHEN UPDATING THEN ''U'' ELSE ''D'' END,' || l_lf
               || '            p_old_data   => l_old,' || l_lf
               || '            p_new_data   => l_new);' || l_lf
               || '    END IF;' || l_lf;
        END IF;

        l_body := l_body || 'END;';

        EXECUTE IMMEDIATE l_body;
    END CREATE_TABLE_TRIGGER;

    PROCEDURE CREATE_ALL_TRIGGERS (p_table_like IN VARCHAR2 DEFAULT 'MOINFO\_%') IS
    BEGIN
        FOR r IN (SELECT t.TABLE_NAME
                    FROM USER_TABLES t
                   WHERE t.TABLE_NAME LIKE p_table_like ESCAPE '\'
                     AND EXISTS (SELECT 1
                                   FROM USER_CONSTRAINTS c
                                  WHERE c.TABLE_NAME = t.TABLE_NAME
                                    AND c.CONSTRAINT_TYPE = 'P')
                   ORDER BY t.TABLE_NAME)
        LOOP
            IF NOT is_excluded(r.TABLE_NAME) THEN
                CREATE_TABLE_TRIGGER(r.TABLE_NAME, CASE WHEN audit_disabled(r.TABLE_NAME) THEN 'N' ELSE 'Y' END);
            END IF;
        END LOOP;
    END CREATE_ALL_TRIGGERS;

END MOINFO_UTIL;
