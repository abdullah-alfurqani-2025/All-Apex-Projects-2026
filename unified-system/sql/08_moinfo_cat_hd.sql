CREATE OR REPLACE VIEW MOINFO_CAT_V_MODELS AS
SELECT m.MODEL_ID,
       m.BRAND_ID,
       b.NAME AS BRAND_NAME,
       m.PRODUCT_TYPE_ID,
       t.NAME_AR AS PRODUCT_TYPE_AR,
       m.NAME AS MODEL_NAME,
       b.NAME || ' ' || m.NAME AS FULL_NAME,
       m.IS_ACTIVE
  FROM MOINFO_CAT_MODELS m
  JOIN MOINFO_CAT_BRANDS b             ON b.BRAND_ID = m.BRAND_ID
  LEFT JOIN MOINFO_CAT_PRODUCT_TYPES t ON t.PRODUCT_TYPE_ID = m.PRODUCT_TYPE_ID;

CREATE OR REPLACE VIEW MOINFO_HD_V_DEVICES AS
SELECT d.DEVICE_ID,
       d.SERIAL_NO,
       d.SERVICE_TAG,
       d.DEVICE_NAME,
       d.MODEL_ID,
       m.BRAND_NAME,
       m.MODEL_NAME,
       m.PRODUCT_TYPE_AR,
       d.SUPPLIER_ID,
       s.NAME_AR AS SUPPLIER_AR,
       d.PO_ID,
       po.PO_NO,
       d.WARRANTY_TYPE_ID,
       w.NAME_AR AS WARRANTY_TYPE_AR,
       d.WARRANTY_START,
       d.WARRANTY_END,
       d.WARRANTY_END - TRUNC(SYSDATE) AS WARRANTY_DAYS_LEFT,
       CASE
           WHEN d.WARRANTY_END IS NULL THEN NULL
           WHEN d.WARRANTY_END < TRUNC(SYSDATE) THEN 'منتهي'
           ELSE 'ساري'
       END AS WARRANTY_STATE_AR,
       d.STATUS_ID,
       st.LOOKUP_CODE AS STATUS_CODE,
       st.NAME_AR AS STATUS_AR,
       d.CURRENT_EMPLOYEE_ID,
       e.NAME_AR AS CURRENT_EMPLOYEE_AR,
       e.EMPLOYEE_NO AS CURRENT_EMPLOYEE_NO,
       d.CURRENT_UNIT_ID,
       u.UNIT_PATH_AR AS CURRENT_UNIT_AR,
       d.REMARKS,
       d.IS_ACTIVE,
       (SELECT COUNT(*) FROM MOINFO_HD_SPARE_PARTS p WHERE p.DEVICE_ID = d.DEVICE_ID) AS PARTS_COUNT,
       (SELECT COUNT(*) FROM MOINFO_HD_REQUESTS r WHERE r.DEVICE_ID = d.DEVICE_ID) AS REQUESTS_COUNT
  FROM MOINFO_HD_DEVICES d
  JOIN MOINFO_LOOKUPS st               ON st.LOOKUP_ID = d.STATUS_ID
  LEFT JOIN MOINFO_CAT_V_MODELS m      ON m.MODEL_ID = d.MODEL_ID
  LEFT JOIN MOINFO_CAT_SUPPLIERS s     ON s.SUPPLIER_ID = d.SUPPLIER_ID
  LEFT JOIN MOINFO_HD_PURCHASE_ORDERS po ON po.PO_ID = d.PO_ID
  LEFT JOIN MOINFO_CAT_WARRANTY_TYPES w ON w.WARRANTY_TYPE_ID = d.WARRANTY_TYPE_ID
  LEFT JOIN MOINFO_EMPLOYEES e         ON e.EMPLOYEE_ID = d.CURRENT_EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS u           ON u.UNIT_ID = d.CURRENT_UNIT_ID;

-- سجل التسليم مع الأسماء
CREATE OR REPLACE VIEW MOINFO_HD_V_ASSIGNMENTS AS
SELECT a.ASSIGNMENT_ID,
       a.DEVICE_ID,
       d.SERIAL_NO,
       d.DEVICE_NAME,
       a.EMPLOYEE_ID,
       e.NAME_AR AS EMPLOYEE_AR,
       e.EMPLOYEE_NO,
       a.UNIT_ID,
       u.UNIT_PATH_AR AS UNIT_AR,
       a.ASSIGNED_DATE,
       a.RETURN_DATE,
       CASE WHEN a.RETURN_DATE IS NULL THEN 'Y' ELSE 'N' END AS IS_CURRENT,
       NVL(a.RETURN_DATE, TRUNC(SYSDATE)) - a.ASSIGNED_DATE AS DAYS_HELD,
       a.REMARKS
  FROM MOINFO_HD_ASSIGNMENTS a
  JOIN MOINFO_HD_DEVICES d   ON d.DEVICE_ID = a.DEVICE_ID
  LEFT JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = a.EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS u   ON u.UNIT_ID = a.UNIT_ID;

-- الأجهزة وقطع الغيار التي ينتهي ضمانها (الإعداد HD_WARRANTY_ALERT_DAYS، الافتراضي 60 يومًا)
CREATE OR REPLACE VIEW MOINFO_HD_V_WARRANTY_EXPIRING AS
SELECT 'جهاز' AS ITEM_KIND_AR,
       d.DEVICE_ID,
       d.SERIAL_NO,
       NVL(d.DEVICE_NAME, d.BRAND_NAME || ' ' || d.MODEL_NAME) AS ITEM_NAME,
       d.SUPPLIER_AR,
       d.WARRANTY_END,
       d.WARRANTY_DAYS_LEFT AS DAYS_LEFT,
       d.CURRENT_EMPLOYEE_AR
  FROM MOINFO_HD_V_DEVICES d
 WHERE d.IS_ACTIVE = 'Y'
   AND d.WARRANTY_END IS NOT NULL
   AND d.WARRANTY_END <= TRUNC(SYSDATE) + TO_NUMBER(NVL((SELECT SETTING_VALUE FROM MOINFO_SETTINGS WHERE SETTING_KEY = 'HD_WARRANTY_ALERT_DAYS'), '60'))
UNION ALL
SELECT 'قطعة غيار',
       p.DEVICE_ID,
       NVL(p.PART_SN, d.SERIAL_NO),
       p.PART_NAME,
       s.NAME_AR,
       p.WARRANTY_END,
       p.WARRANTY_END - TRUNC(SYSDATE),
       e.NAME_AR
  FROM MOINFO_HD_SPARE_PARTS p
  JOIN MOINFO_HD_DEVICES d ON d.DEVICE_ID = p.DEVICE_ID
  LEFT JOIN MOINFO_CAT_SUPPLIERS s ON s.SUPPLIER_ID = p.SUPPLIER_ID
  LEFT JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = d.CURRENT_EMPLOYEE_ID
 WHERE p.WARRANTY_END IS NOT NULL
   AND p.WARRANTY_END <= TRUNC(SYSDATE) + TO_NUMBER(NVL((SELECT SETTING_VALUE FROM MOINFO_SETTINGS WHERE SETTING_KEY = 'HD_WARRANTY_ALERT_DAYS'), '60'));

CREATE OR REPLACE VIEW MOINFO_HD_V_REQUESTS AS
SELECT r.REQUEST_ID,
       r.TITLE,
       r.DESCRIPTION,
       r.REQUESTER_EMPLOYEE_ID,
       re.NAME_AR AS REQUESTER_AR,
       re.EMPLOYEE_NO AS REQUESTER_NO,
       re.UNIT_ID AS REQUESTER_UNIT_ID,
       ru.UNIT_PATH_AR AS REQUESTER_UNIT_AR,
       re.PHONE_EXT AS REQUESTER_EXT,
       r.DEVICE_ID,
       d.SERIAL_NO,
       d.DEVICE_NAME,
       r.STATUS_ID,
       st.LOOKUP_CODE AS STATUS_CODE,
       st.NAME_AR AS STATUS_AR,
       CASE WHEN st.LOOKUP_CODE IN ('DONE', 'CANCELLED') THEN 'Y' ELSE 'N' END AS IS_CLOSED,
       r.ASSIGNED_EMPLOYEE_ID,
       ae.NAME_AR AS ASSIGNED_AR,
       r.REQUEST_DATE,
       r.CLOSED_DATE,
       NVL(r.CLOSED_DATE, TRUNC(SYSDATE)) - r.REQUEST_DATE AS DURATION_DAYS,
       r.SOLUTION,
       r.IS_ACTIVE,
       r.CREATED_BY,
       r.CREATED_AT
  FROM MOINFO_HD_REQUESTS r
  JOIN MOINFO_LOOKUPS st        ON st.LOOKUP_ID = r.STATUS_ID
  JOIN MOINFO_EMPLOYEES re      ON re.EMPLOYEE_ID = r.REQUESTER_EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS ru   ON ru.UNIT_ID = re.UNIT_ID
  LEFT JOIN MOINFO_HD_DEVICES d ON d.DEVICE_ID = r.DEVICE_ID
  LEFT JOIN MOINFO_EMPLOYEES ae ON ae.EMPLOYEE_ID = r.ASSIGNED_EMPLOYEE_ID;

CREATE OR REPLACE VIEW MOINFO_HD_V_REQUEST_NOTES AS
SELECT n.NOTE_ID,
       n.REQUEST_ID,
       n.NOTE_TEXT,
       n.STATUS_ID,
       st.NAME_AR AS STATUS_AR,
       n.CREATED_BY,
       NVL(u.DISPLAY_NAME, n.CREATED_BY) AS CREATED_BY_NAME,
       n.CREATED_AT
  FROM MOINFO_HD_REQUEST_NOTES n
  LEFT JOIN MOINFO_LOOKUPS st ON st.LOOKUP_ID = n.STATUS_ID
  LEFT JOIN MOINFO_USERS u    ON u.USERNAME = n.CREATED_BY;


