--   PRT_HD_REQUESTS         ← MOINFO_HD_REQUESTS
--   PRT_HD_REMARKS          ← MOINFO_HD_REQUEST_NOTES
--   PRT_HD_STATUS           ← MOINFO_LOOKUPS (HD_REQUEST_STATUS و HD_DEVICE_STATUS)
--   PRT_HD_USER_INFO / PRIVILEGES / *_IT ← النواة
--
-- الصلاحيات في وحدة HD:
--   USER    + OWN  : الموظف يرفع طلب دعم ويتابع طلباته
--   MANAGER + UNIT : فني الدعم يدير الأجهزة والطلبات
--   ADMIN   + ALL  : كل شيء
