CREATE TABLE MOINFO_TSK_TASKS (
    TASK_ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REF_NO                  VARCHAR2(50 CHAR),
    TITLE                   VARCHAR2(500 CHAR)  NOT NULL,
    DESCRIPTION             VARCHAR2(2000 CHAR),
    TASK_TYPE_ID            NUMBER,
    TASK_CATEGORY_ID        NUMBER,
    STATUS_ID               NUMBER              NOT NULL,
    PRIORITY                VARCHAR2(10) DEFAULT ON NULL 'NORMAL' NOT NULL,
    ASSIGNED_EMPLOYEE_ID    NUMBER,
    REQUESTER_EMPLOYEE_ID   NUMBER,
    REQUESTER_NAME          VARCHAR2(300 CHAR),
    RECEIVED_DATE           DATE DEFAULT ON NULL TRUNC(SYSDATE) NOT NULL,
    DUE_DATE                DATE,
    CLOSED_DATE             DATE,
    ACTION_TAKEN            VARCHAR2(2000 CHAR),
    IS_ACTIVE               VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY              VARCHAR2(255),
    CREATED_AT              TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY              VARCHAR2(255),
    UPDATED_AT              TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_TSK_TASKS_PK PRIMARY KEY (TASK_ID),
    CONSTRAINT MOINFO_TSK_TASKS_TYPE_FK FOREIGN KEY (TASK_TYPE_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_TSK_TASKS_CAT_FK FOREIGN KEY (TASK_CATEGORY_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_TSK_TASKS_STATUS_FK FOREIGN KEY (STATUS_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_TSK_TASKS_ASSIGNED_FK FOREIGN KEY (ASSIGNED_EMPLOYEE_ID) REFERENCES MOINFO_EMPLOYEES (EMPLOYEE_ID),
    CONSTRAINT MOINFO_TSK_TASKS_REQUESTER_FK FOREIGN KEY (REQUESTER_EMPLOYEE_ID) REFERENCES MOINFO_EMPLOYEES (EMPLOYEE_ID),
    CONSTRAINT MOINFO_TSK_TASKS_PRIORITY_CK CHECK (PRIORITY IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT MOINFO_TSK_TASKS_CLOSED_CK CHECK (CLOSED_DATE IS NULL OR CLOSED_DATE >= RECEIVED_DATE),
    CONSTRAINT MOINFO_TSK_TASKS_DUE_CK CHECK (DUE_DATE IS NULL OR DUE_DATE >= RECEIVED_DATE),
    CONSTRAINT MOINFO_TSK_TASKS_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_TSK_TASKS_ASSIGNED_IX  ON MOINFO_TSK_TASKS (ASSIGNED_EMPLOYEE_ID, STATUS_ID);
CREATE INDEX MOINFO_TSK_TASKS_REQUESTER_IX ON MOINFO_TSK_TASKS (REQUESTER_EMPLOYEE_ID);
CREATE INDEX MOINFO_TSK_TASKS_STATUS_IX    ON MOINFO_TSK_TASKS (STATUS_ID);
CREATE INDEX MOINFO_TSK_TASKS_TYPE_IX      ON MOINFO_TSK_TASKS (TASK_TYPE_ID);
CREATE INDEX MOINFO_TSK_TASKS_CAT_IX       ON MOINFO_TSK_TASKS (TASK_CATEGORY_ID);
CREATE INDEX MOINFO_TSK_TASKS_RECEIVED_IX  ON MOINFO_TSK_TASKS (RECEIVED_DATE);
CREATE INDEX MOINFO_TSK_TASKS_REF_IX       ON MOINFO_TSK_TASKS (REF_NO);

-- سجل متابعة المهمة: ملاحظة لكل تحديث، ومعها الحالة الجديدة إن تغيّرت
CREATE TABLE MOINFO_TSK_NOTES (
    NOTE_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TASK_ID         NUMBER                      NOT NULL,
    NOTE_TEXT       VARCHAR2(2000 CHAR)         NOT NULL,
    STATUS_ID       NUMBER,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_TSK_NOTES_PK PRIMARY KEY (NOTE_ID),
    CONSTRAINT MOINFO_TSK_NOTES_TASK_FK FOREIGN KEY (TASK_ID) REFERENCES MOINFO_TSK_TASKS (TASK_ID) ON DELETE CASCADE,
    CONSTRAINT MOINFO_TSK_NOTES_STATUS_FK FOREIGN KEY (STATUS_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID)
