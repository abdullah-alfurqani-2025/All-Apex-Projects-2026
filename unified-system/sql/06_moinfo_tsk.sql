-- المهام مع كل الأسماء والمدة
-- مثال في الصفحة: SELECT * FROM MOINFO_TSK_V_TASKS WHERE MOINFO_TSK.CAN_SEE(TASK_ID) = 'Y'
CREATE OR REPLACE VIEW MOINFO_TSK_V_TASKS AS
SELECT t.TASK_ID,
       t.REF_NO,
       t.TITLE,
       t.DESCRIPTION,
       t.TASK_TYPE_ID,
       typ.NAME_AR AS TASK_TYPE_AR,
       t.TASK_CATEGORY_ID,
       cat.NAME_AR AS TASK_CATEGORY_AR,
       t.STATUS_ID,
       st.LOOKUP_CODE AS STATUS_CODE,
       st.NAME_AR AS STATUS_AR,
       CASE WHEN st.LOOKUP_CODE IN ('DONE', 'CANCELLED') THEN 'Y' ELSE 'N' END AS IS_CLOSED,
       t.PRIORITY,
       CASE t.PRIORITY
           WHEN 'LOW'    THEN 'منخفضة'
           WHEN 'NORMAL' THEN 'عادية'
           WHEN 'HIGH'   THEN 'عالية'
           WHEN 'URGENT' THEN 'عاجلة'
       END AS PRIORITY_AR,
       t.ASSIGNED_EMPLOYEE_ID,
       ae.NAME_AR AS ASSIGNED_NAME_AR,
       ae.UNIT_ID AS ASSIGNED_UNIT_ID,
       t.REQUESTER_EMPLOYEE_ID,
       NVL(re.NAME_AR, t.REQUESTER_NAME) AS REQUESTER_NAME_AR,
       ru.UNIT_PATH_AR AS REQUESTER_UNIT_AR,
       t.RECEIVED_DATE,
       t.DUE_DATE,
       t.CLOSED_DATE,
       NVL(t.CLOSED_DATE, TRUNC(SYSDATE)) - t.RECEIVED_DATE AS DURATION_DAYS,
       CASE
           WHEN t.DUE_DATE IS NOT NULL
            AND NVL(t.CLOSED_DATE, TRUNC(SYSDATE)) > t.DUE_DATE
           THEN 'Y' ELSE 'N'
       END AS IS_LATE,
       t.ACTION_TAKEN,
       t.IS_ACTIVE,
       t.CREATED_BY,
       t.CREATED_AT,
       t.UPDATED_BY,
       t.UPDATED_AT
  FROM MOINFO_TSK_TASKS t
  JOIN MOINFO_LOOKUPS st          ON st.LOOKUP_ID = t.STATUS_ID
  LEFT JOIN MOINFO_LOOKUPS typ    ON typ.LOOKUP_ID = t.TASK_TYPE_ID
  LEFT JOIN MOINFO_LOOKUPS cat    ON cat.LOOKUP_ID = t.TASK_CATEGORY_ID
  LEFT JOIN MOINFO_EMPLOYEES ae   ON ae.EMPLOYEE_ID = t.ASSIGNED_EMPLOYEE_ID
  LEFT JOIN MOINFO_EMPLOYEES re   ON re.EMPLOYEE_ID = t.REQUESTER_EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS ru     ON ru.UNIT_ID = re.UNIT_ID;

-- ملاحظات المتابعة مع اسم كاتبها
CREATE OR REPLACE VIEW MOINFO_TSK_V_NOTES AS
SELECT n.NOTE_ID,
       n.TASK_ID,
       n.NOTE_TEXT,
       n.STATUS_ID,
       st.NAME_AR AS STATUS_AR,
       n.CREATED_BY,
       NVL(u.DISPLAY_NAME, n.CREATED_BY) AS CREATED_BY_NAME,
       n.CREATED_AT
  FROM MOINFO_TSK_NOTES n
  LEFT JOIN MOINFO_LOOKUPS st ON st.LOOKUP_ID = n.STATUS_ID
  LEFT JOIN MOINFO_USERS u    ON u.USERNAME = n.CREATED_BY;

-- إحصائيات لكل موظف مكلّف حسب الشهر (بديل Chart Report و Monitor Report)
CREATE OR REPLACE VIEW MOINFO_TSK_V_STATS AS
SELECT t.ASSIGNED_EMPLOYEE_ID,
       ae.NAME_AR AS ASSIGNED_NAME_AR,
       ae.UNIT_ID AS ASSIGNED_UNIT_ID,
       TRUNC(t.RECEIVED_DATE, 'MM') AS RECEIVED_MONTH,
       COUNT(*) AS TASKS_COUNT,
       SUM(CASE WHEN st.LOOKUP_CODE = 'DONE' THEN 1 ELSE 0 END) AS DONE_COUNT,
       SUM(CASE WHEN st.LOOKUP_CODE NOT IN ('DONE', 'CANCELLED') THEN 1 ELSE 0 END) AS OPEN_COUNT,
       ROUND(AVG(CASE WHEN st.LOOKUP_CODE = 'DONE' THEN t.CLOSED_DATE - t.RECEIVED_DATE END), 1) AS AVG_DAYS_TO_CLOSE
  FROM MOINFO_TSK_TASKS t
  JOIN MOINFO_LOOKUPS st        ON st.LOOKUP_ID = t.STATUS_ID
  LEFT JOIN MOINFO_EMPLOYEES ae ON ae.EMPLOYEE_ID = t.ASSIGNED_EMPLOYEE_ID
 WHERE t.IS_ACTIVE = 'Y'
 GROUP BY t.ASSIGNED_EMPLOYEE_ID, ae.NAME_AR, ae.UNIT_ID, TRUNC(t.RECEIVED_DATE, 'MM');


