--==============================================================================
-- 3) Trigger قاعدة الإغلاق
--   منفصل عن Trigger التدقيق المولّد (MOINFO_TSK_TASKS_BIUD) حتى لا يُستبدل
--   عند إعادة تشغيل المولّد.
--   الحالة المغلقة (DONE / CANCELLED) بلا تاريخ إغلاق ← يُعبّأ بتاريخ اليوم
--   الحالة المفتوحة ← يُمسح تاريخ الإغلاق (إعادة فتح المهمة)
--==============================================================================
CREATE OR REPLACE TRIGGER MOINFO_TSK_TASKS_CLOSE_BIU
BEFORE INSERT OR UPDATE OF STATUS_ID, CLOSED_DATE ON MOINFO_TSK_TASKS
FOR EACH ROW
DECLARE
    l_code MOINFO_LOOKUPS.LOOKUP_CODE%TYPE;
BEGIN
    SELECT LOOKUP_CODE INTO l_code FROM MOINFO_LOOKUPS WHERE LOOKUP_ID = :NEW.STATUS_ID;

    IF l_code IN ('DONE', 'CANCELLED') THEN
        IF :NEW.CLOSED_DATE IS NULL THEN
            :NEW.CLOSED_DATE := GREATEST(TRUNC(SYSDATE), :NEW.RECEIVED_DATE);
        END IF;
    ELSE
        :NEW.CLOSED_DATE := NULL;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
END;
/


