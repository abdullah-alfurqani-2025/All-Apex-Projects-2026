CREATE INDEX MOINFO_TSK_NOTES_TASK_IX   ON MOINFO_TSK_NOTES (TASK_ID, CREATED_AT);
CREATE INDEX MOINFO_TSK_NOTES_STATUS_IX ON MOINFO_TSK_NOTES (STATUS_ID);

