-- 4) MOINFO_TSK: دوال الوحدة
--==============================================================================
CREATE OR REPLACE PACKAGE MOINFO_TSK AS

    -- 'Y' إن كان يحق للمستخدم الحالي رؤية المهمة
    -- مثال: WHERE MOINFO_TSK.CAN_SEE(TASK_ID) = 'Y'
    FUNCTION CAN_SEE (p_task_id IN NUMBER) RETURN VARCHAR2;

    -- رقم حالة من رمزها، مثل GET_STATUS_ID('NEW') لقيمة افتراضية في نموذج الإدخال
    FUNCTION GET_STATUS_ID (p_code IN VARCHAR2) RETURN NUMBER;

    -- يضيف ملاحظة متابعة، ويغيّر حالة المهمة إن أُرسلت حالة جديدة
    PROCEDURE ADD_NOTE (
        p_task_id   IN NUMBER,
        p_note_text IN VARCHAR2,
        p_status_id IN NUMBER DEFAULT NULL
    );

END MOINFO_TSK;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_TSK AS

    FUNCTION CAN_SEE (p_task_id IN NUMBER) RETURN VARCHAR2 IS
        l_scope       VARCHAR2(10);
        l_assigned    NUMBER;
        l_created_by  VARCHAR2(255);
        l_unit_id     NUMBER;
        l_my_emp      NUMBER;
        l_me          VARCHAR2(255) := UPPER(TRIM(V('APP_USER')));
    BEGIN
        l_scope := MOINFO_SEC.DATA_SCOPE('TSK');

        IF l_scope = 'ALL' THEN
            RETURN 'Y';
        ELSIF l_scope IS NULL THEN
            RETURN 'N';
        END IF;

        SELECT t.ASSIGNED_EMPLOYEE_ID, t.CREATED_BY, e.UNIT_ID
          INTO l_assigned, l_created_by, l_unit_id
          FROM MOINFO_TSK_TASKS t
          LEFT JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = t.ASSIGNED_EMPLOYEE_ID
         WHERE t.TASK_ID = p_task_id;

        -- المهام المكلّف بها المستخدم أو التي أنشأها مرئية له في كل النطاقات
        l_my_emp := MOINFO_HR.MY_EMPLOYEE_ID;
        IF (l_assigned IS NOT NULL AND l_assigned = l_my_emp) OR UPPER(l_created_by) = l_me THEN
            RETURN 'Y';
        END IF;

        IF l_scope = 'UNIT' AND l_unit_id IS NOT NULL THEN
            RETURN MOINFO_SEC.CAN_SEE_UNIT('TSK', l_unit_id);
        END IF;

        RETURN 'N';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 'N';
    END CAN_SEE;

    FUNCTION GET_STATUS_ID (p_code IN VARCHAR2) RETURN NUMBER IS
        l_id NUMBER;
    BEGIN
        SELECT LOOKUP_ID
          INTO l_id
          FROM MOINFO_LOOKUPS
         WHERE LOOKUP_TYPE = 'TSK_STATUS'
           AND LOOKUP_CODE = UPPER(p_code);
        RETURN l_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END GET_STATUS_ID;

    PROCEDURE ADD_NOTE (
        p_task_id   IN NUMBER,
        p_note_text IN VARCHAR2,
        p_status_id IN NUMBER DEFAULT NULL
    ) IS
    BEGIN
        INSERT INTO MOINFO_TSK_NOTES (TASK_ID, NOTE_TEXT, STATUS_ID)
        VALUES (p_task_id, p_note_text, p_status_id);

        IF p_status_id IS NOT NULL THEN
            UPDATE MOINFO_TSK_TASKS
               SET STATUS_ID = p_status_id
             WHERE TASK_ID = p_task_id
               AND STATUS_ID <> p_status_id;
        END IF;
    END ADD_NOTE;

END MOINFO_TSK;
/


