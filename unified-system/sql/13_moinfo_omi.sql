CREATE OR REPLACE VIEW MOINFO_OMI_V_TERMINALS AS
SELECT t.TERMINAL_ID,
       t.SERIAL_NO,
       t.NAME,
       t.MAC_ADDRESS,
       t.IP_ADDRESS,
       t.SITE_ID,
       s.NAME_AR AS SITE_AR,
       t.REG_POINT_ID,
       p.NAME_AR AS REG_POINT_AR,
       t.LOCATION_DESC,
       t.IS_FIXED,
       t.IS_CONNECTED,
       t.REMARKS,
       t.IS_ACTIVE,
       (SELECT COUNT(*) FROM MOINFO_OMI_PERSONS x WHERE x.TERMINAL_ID = t.TERMINAL_ID AND x.IS_REGISTERED = 'Y') AS PERSONS_COUNT
  FROM MOINFO_OMI_TERMINALS t
  LEFT JOIN MOINFO_LOOKUPS s ON s.LOOKUP_ID = t.SITE_ID
  LEFT JOIN MOINFO_LOOKUPS p ON p.LOOKUP_ID = t.REG_POINT_ID;

CREATE OR REPLACE VIEW MOINFO_OMI_V_PERSONS AS
SELECT x.PERSON_ID,
       x.EMPLOYEE_ID,
       x.EMP_NO,
       x.WORK_ID,
       x.NAME_AR,
       x.NAME_EN,
       x.CIVIL_NO,
       x.SITE_ID,
       s.LOOKUP_CODE AS SITE_CODE,
       s.NAME_AR AS SITE_AR,
       u.UNIT_PATH_AR AS UNIT_AR,
       x.IS_REGISTERED,
       CASE x.IS_REGISTERED WHEN 'Y' THEN 'مسجّل' ELSE 'غير مسجّل' END AS REGISTERED_AR,
       x.REGISTERED_AT,
       x.REG_POINT_ID,
       p.NAME_AR AS REG_POINT_AR,
       x.TERMINAL_ID,
       t.NAME AS TERMINAL_NAME,
       t.SERIAL_NO AS TERMINAL_SN,
       x.IS_UPLOADED,
       CASE x.IS_UPLOADED WHEN 'Y' THEN 'مرفوع' ELSE 'غير مرفوع' END AS UPLOADED_AR,
       x.UPLOADED_AT,
       x.REMARKS,
       x.IS_ACTIVE,
       x.CREATED_BY,
       x.CREATED_AT
  FROM MOINFO_OMI_PERSONS x
  LEFT JOIN MOINFO_LOOKUPS s        ON s.LOOKUP_ID = x.SITE_ID
  LEFT JOIN MOINFO_LOOKUPS p        ON p.LOOKUP_ID = x.REG_POINT_ID
  LEFT JOIN MOINFO_OMI_TERMINALS t  ON t.TERMINAL_ID = x.TERMINAL_ID
  LEFT JOIN MOINFO_EMPLOYEES e      ON e.EMPLOYEE_ID = x.EMPLOYEE_ID
  LEFT JOIN MOINFO_V_UNITS u        ON u.UNIT_ID = e.UNIT_ID;

-- التسجيل اليومي حسب الموقع ونقطة التسجيل
CREATE OR REPLACE VIEW MOINFO_OMI_V_DAILY AS
SELECT TRUNC(x.REGISTERED_AT) AS REG_DAY,
       x.SITE_AR,
       x.REG_POINT_AR,
       COUNT(*) AS REGISTERED_COUNT,
       SUM(CASE WHEN x.IS_UPLOADED = 'Y' THEN 1 ELSE 0 END) AS UPLOADED_COUNT
  FROM MOINFO_OMI_V_PERSONS x
 WHERE x.IS_REGISTERED = 'Y'
 GROUP BY TRUNC(x.REGISTERED_AT), x.SITE_AR, x.REG_POINT_AR;

-- الملخص حسب الموقع
CREATE OR REPLACE VIEW MOINFO_OMI_V_SUMMARY AS
SELECT x.SITE_ID,
       NVL(x.SITE_AR, 'بلا موقع') AS SITE_AR,
       COUNT(*) AS PERSONS_COUNT,
       SUM(CASE WHEN x.IS_REGISTERED = 'Y' THEN 1 ELSE 0 END) AS REGISTERED_COUNT,
       SUM(CASE WHEN x.IS_REGISTERED = 'N' THEN 1 ELSE 0 END) AS NOT_REGISTERED_COUNT,
       SUM(CASE WHEN x.IS_REGISTERED = 'Y' AND x.IS_UPLOADED = 'N' THEN 1 ELSE 0 END) AS NOT_UPLOADED_COUNT,
       SUM(CASE WHEN TRUNC(x.REGISTERED_AT) = TRUNC(SYSDATE) THEN 1 ELSE 0 END) AS TODAY_COUNT
  FROM MOINFO_OMI_V_PERSONS x
 WHERE x.IS_ACTIVE = 'Y'
 GROUP BY x.SITE_ID, x.SITE_AR;


