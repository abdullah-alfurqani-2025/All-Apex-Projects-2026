--==============================================================================
-- 3) Trigger القواعد
--==============================================================================
-- الشخص المرتبط بموظف يأخذ اسمه ورقمه إن تُركا فارغين، وتواريخ التسجيل والرفع تُعبّأ وتُمسح مع حالتيهما
CREATE OR REPLACE TRIGGER MOINFO_OMI_PERSONS_RULES_BIU
BEFORE INSERT OR UPDATE ON MOINFO_OMI_PERSONS
FOR EACH ROW
BEGIN
    IF :NEW.EMPLOYEE_ID IS NOT NULL AND (:NEW.NAME_AR IS NULL OR :NEW.EMP_NO IS NULL OR :NEW.NAME_EN IS NULL) THEN
        FOR e IN (SELECT NAME_AR, NAME_EN, EMPLOYEE_NO FROM MOINFO_EMPLOYEES WHERE EMPLOYEE_ID = :NEW.EMPLOYEE_ID) LOOP
            :NEW.NAME_AR := NVL(:NEW.NAME_AR, e.NAME_AR);
            :NEW.NAME_EN := NVL(:NEW.NAME_EN, e.NAME_EN);
            :NEW.EMP_NO  := NVL(:NEW.EMP_NO, e.EMPLOYEE_NO);
        END LOOP;
    END IF;

    IF :NEW.IS_REGISTERED = 'Y' THEN
        :NEW.REGISTERED_AT := NVL(:NEW.REGISTERED_AT, SYSDATE);
    ELSE
        :NEW.REGISTERED_AT := NULL;
        :NEW.IS_UPLOADED := 'N';
    END IF;

    IF :NEW.IS_UPLOADED = 'Y' THEN
        :NEW.UPLOADED_AT := NVL(:NEW.UPLOADED_AT, SYSDATE);
    ELSE
        :NEW.UPLOADED_AT := NULL;
    END IF;

    :NEW.CIVIL_NO := TRIM(:NEW.CIVIL_NO);
END;
/


