-- MOINFO - النظام الموحد
-- السكربت 13: تسجيل البصمة (OMI) — بديل OmanInfo (f1000)
--
-- يُشغَّل بعد 01 إلى 12 في نفس الـ Schema.
--
-- النظام القديم يتابع تسجيل بصمات الأشخاص في أجهزة البصمة ورفعها إلى نظام Alpeta:
--   MOI_EMPLOYEES              ← MOINFO_OMI_PERSONS (يمكن ربط الشخص بموظف في النواة، أو تركه شخصًا خارجيًا)
--   REGISTRATION_STATUS 'Yes/No'       ← IS_REGISTERED + REGISTERED_AT
--   UPLOAD_TO_ALPETA_STATUS 'Yes/No'   ← IS_UPLOADED + UPLOADED_AT
--   LOCATION CHAR(3)           ← MOINFO_LOOKUPS (OMI_SITE): الموقع الجغرافي مثل مسقط وصلالة
--   MOI_REGISTRATION_LOCATIONS ← MOINFO_LOOKUPS (OMI_REG_POINT): نقطة التسجيل
--   MOI_TERMINALS + MOI_FIXED_TERMINALS ← MOINFO_OMI_TERMINALS (جهاز واحد بكل بياناته)
--   *_AUDIT                    ← MOINFO_AUDIT_LOG (التدقيق العام)
--   MOI_USERS / PRIVILEGES / LOGINHISTORY ← النواة
--
-- الصلاحيات في وحدة OMI:
--   VIEWER  : يطّلع
--   USER    : يضيف الأشخاص ويسجّل البصمة
--   MANAGER : يؤكد الرفع إلى Alpeta، ويدير الأجهزة والقوائم
--------------------------------------------------------------------------------


