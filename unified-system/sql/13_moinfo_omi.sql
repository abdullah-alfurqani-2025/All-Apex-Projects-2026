CREATE TABLE MOINFO_OMI_TERMINALS (
    TERMINAL_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SERIAL_NO       VARCHAR2(100)               NOT NULL,
    NAME            VARCHAR2(100 CHAR),
    MAC_ADDRESS     VARCHAR2(100),
    IP_ADDRESS      VARCHAR2(100),
    SITE_ID         NUMBER,
    REG_POINT_ID    NUMBER,
    LOCATION_DESC   VARCHAR2(200 CHAR),
    IS_FIXED        VARCHAR2(1) DEFAULT ON NULL 'N' NOT NULL,
    IS_CONNECTED    VARCHAR2(1) DEFAULT ON NULL 'N' NOT NULL,
    REMARKS         VARCHAR2(500 CHAR),
    IS_ACTIVE       VARCHAR2(1) DEFAULT ON NULL 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(255),
    CREATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    UPDATED_BY      VARCHAR2(255),
    UPDATED_AT      TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT MOINFO_OMI_TERM_PK PRIMARY KEY (TERMINAL_ID),
    CONSTRAINT MOINFO_OMI_TERM_SN_UK UNIQUE (SERIAL_NO),
    CONSTRAINT MOINFO_OMI_TERM_SITE_FK FOREIGN KEY (SITE_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_OMI_TERM_POINT_FK FOREIGN KEY (REG_POINT_ID) REFERENCES MOINFO_LOOKUPS (LOOKUP_ID),
    CONSTRAINT MOINFO_OMI_TERM_FIXED_CK CHECK (IS_FIXED IN ('Y','N')),
    CONSTRAINT MOINFO_OMI_TERM_CONN_CK CHECK (IS_CONNECTED IN ('Y','N')),
    CONSTRAINT MOINFO_OMI_TERM_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX MOINFO_OMI_TERM_SITE_IX  ON MOINFO_OMI_TERMINALS (SITE_ID);
CREATE INDEX MOINFO_OMI_TERM_POINT_IX ON MOINFO_OMI_TERMINALS (REG_POINT_ID);

