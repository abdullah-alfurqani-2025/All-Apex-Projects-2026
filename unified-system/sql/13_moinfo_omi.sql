CREATE OR REPLACE PACKAGE MOINFO_OMI AS

    -- 'Y' إن كان للمستخدم الحالي دور USER فأعلى (إضافة الأشخاص وتسجيل البصمة)
    FUNCTION CAN_REGISTER RETURN VARCHAR2;

    -- 'Y' إن كان للمستخدم الحالي دور MANAGER فأعلى (الرفع إلى Alpeta والأجهزة والقوائم)
    FUNCTION IS_MANAGER RETURN VARCHAR2;

    -- يسجّل بصمة الشخص الآن (أو في التاريخ المرسل) من نقطة تسجيل وجهاز
    PROCEDURE REGISTER_PERSON (
        p_person_id   IN NUMBER,
        p_point_id    IN NUMBER DEFAULT NULL,
        p_terminal_id IN NUMBER DEFAULT NULL,
        p_date        IN DATE   DEFAULT SYSDATE
    );

    -- يلغي تسجيل البصمة (ويلغي الرفع معه)
    PROCEDURE UNREGISTER_PERSON (p_person_id IN NUMBER);

    -- يؤكد رفع بصمة شخص مسجَّل إلى Alpeta
    PROCEDURE MARK_UPLOADED (p_person_id IN NUMBER);

    -- يؤكد رفع كل المسجَّلين غير المرفوعين (أو موقع واحد)، ويُرجع عددهم
    FUNCTION MARK_ALL_UPLOADED (p_site_id IN NUMBER DEFAULT NULL) RETURN NUMBER;

END MOINFO_OMI;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_OMI AS

    FUNCTION CAN_REGISTER RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN MOINFO_SEC.HAS_ROLE('OMI', 'USER') THEN 'Y' ELSE 'N' END;
    END CAN_REGISTER;

    FUNCTION IS_MANAGER RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN MOINFO_SEC.HAS_ROLE('OMI', 'MANAGER') THEN 'Y' ELSE 'N' END;
    END IS_MANAGER;

    PROCEDURE REGISTER_PERSON (
        p_person_id   IN NUMBER,
        p_point_id    IN NUMBER DEFAULT NULL,
        p_terminal_id IN NUMBER DEFAULT NULL,
        p_date        IN DATE   DEFAULT SYSDATE
    ) IS
        l_point NUMBER := p_point_id;
    BEGIN
        IF CAN_REGISTER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20110, 'لا تملك صلاحية تسجيل البصمة');
        END IF;
        IF l_point IS NULL AND p_terminal_id IS NOT NULL THEN
            SELECT MAX(REG_POINT_ID) INTO l_point FROM MOINFO_OMI_TERMINALS WHERE TERMINAL_ID = p_terminal_id;
        END IF;
        UPDATE MOINFO_OMI_PERSONS
           SET IS_REGISTERED = 'Y',
               REGISTERED_AT = NVL(p_date, SYSDATE),
               REG_POINT_ID  = NVL(l_point, REG_POINT_ID),
               TERMINAL_ID   = NVL(p_terminal_id, TERMINAL_ID)
         WHERE PERSON_ID = p_person_id;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20111, 'الشخص غير موجود');
        END IF;
    END REGISTER_PERSON;

    PROCEDURE UNREGISTER_PERSON (p_person_id IN NUMBER) IS
    BEGIN
        IF CAN_REGISTER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20110, 'لا تملك صلاحية تسجيل البصمة');
        END IF;
        UPDATE MOINFO_OMI_PERSONS SET IS_REGISTERED = 'N' WHERE PERSON_ID = p_person_id;
    END UNREGISTER_PERSON;

    PROCEDURE MARK_UPLOADED (p_person_id IN NUMBER) IS
        l_reg VARCHAR2(1);
    BEGIN
        IF IS_MANAGER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20112, 'تأكيد الرفع إلى Alpeta للمشرف');
        END IF;
        SELECT IS_REGISTERED INTO l_reg FROM MOINFO_OMI_PERSONS WHERE PERSON_ID = p_person_id;
        IF l_reg = 'N' THEN
            RAISE_APPLICATION_ERROR(-20113, 'سجّل البصمة أولًا قبل تأكيد الرفع');
        END IF;
        UPDATE MOINFO_OMI_PERSONS SET IS_UPLOADED = 'Y' WHERE PERSON_ID = p_person_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20111, 'الشخص غير موجود');
    END MARK_UPLOADED;

    FUNCTION MARK_ALL_UPLOADED (p_site_id IN NUMBER DEFAULT NULL) RETURN NUMBER IS
    BEGIN
        IF IS_MANAGER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20112, 'تأكيد الرفع إلى Alpeta للمشرف');
        END IF;
        UPDATE MOINFO_OMI_PERSONS
           SET IS_UPLOADED = 'Y'
         WHERE IS_REGISTERED = 'Y'
           AND IS_UPLOADED = 'N'
           AND IS_ACTIVE = 'Y'
           AND (p_site_id IS NULL OR SITE_ID = p_site_id);
        RETURN SQL%ROWCOUNT;
    END MARK_ALL_UPLOADED;

END MOINFO_OMI;
/


