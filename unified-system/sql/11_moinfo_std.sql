-- الباركود الافتراضي، والحالة الافتراضية GOOD، ومنع تعديل الرصيد خارج الحزمة
CREATE OR REPLACE TRIGGER MOINFO_STD_ITEMS_RULES_BIU
BEFORE INSERT OR UPDATE ON MOINFO_STD_ITEMS
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF TRIM(:NEW.BARCODE) IS NULL THEN
            :NEW.BARCODE := TO_CHAR(MOINFO_STD_BARCODE_SEQ.NEXTVAL);
        END IF;
        IF :NEW.STATUS_ID IS NULL THEN
            SELECT LOOKUP_ID INTO :NEW.STATUS_ID
              FROM MOINFO_LOOKUPS
             WHERE LOOKUP_TYPE = 'STD_ITEM_STATUS' AND LOOKUP_CODE = 'GOOD';
        END IF;
    ELSIF :NEW.QTY_IN_STOCK <> :OLD.QTY_IN_STOCK AND NOT MOINFO_STD.IN_MOVE THEN
        RAISE_APPLICATION_ERROR(-20082, 'الرصيد يتغير بالحركات فقط (استلام، صرف، إرجاع، تسوية)');
    END IF;
    :NEW.BARCODE := UPPER(TRIM(:NEW.BARCODE));
END;
/

-- الكمية الافتتاحية عند إضافة المعدة تُسجَّل حركة استلام
CREATE OR REPLACE TRIGGER MOINFO_STD_ITEMS_OPENING_AI
AFTER INSERT ON MOINFO_STD_ITEMS
FOR EACH ROW
WHEN (NEW.QTY_IN_STOCK > 0)
BEGIN
    INSERT INTO MOINFO_STD_MOVEMENTS (ITEM_ID, MOVEMENT_TYPE, QTY_CHANGE, BALANCE_AFTER, REMARKS)
    VALUES (:NEW.ITEM_ID, 'IN', :NEW.QTY_IN_STOCK, :NEW.QTY_IN_STOCK, 'رصيد افتتاحي');
END;
/


