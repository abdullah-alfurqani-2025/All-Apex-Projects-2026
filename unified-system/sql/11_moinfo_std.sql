--   VIEWER  : يطّلع على المعدات والحركات
--   USER    : يصرف ويستلم ويُرجع
--   MANAGER : يضيف المعدات ويعدّلها، ويُجري التسوية، ويدير القوائم (المواقع والرفوف والحالات)
