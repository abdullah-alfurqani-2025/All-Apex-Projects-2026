--==============================================================================
-- 3) MOINFO_STD: حركات المخزن
--==============================================================================
CREATE OR REPLACE PACKAGE MOINFO_STD AS

    -- TRUE أثناء تنفيذ حركة من هذه الحزمة؛ يستخدمه Trigger حماية الرصيد
    FUNCTION IN_MOVE RETURN BOOLEAN;

    -- 'Y' إن كان للمستخدم الحالي دور USER فأعلى (صرف واستلام وإرجاع)
    FUNCTION CAN_MOVE RETURN VARCHAR2;

    -- 'Y' إن كان للمستخدم الحالي دور MANAGER فأعلى (المعدات والتسوية والقوائم)
    FUNCTION IS_MANAGER RETURN VARCHAR2;

    -- رقم المعدة من الباركود (أو الرقم التسلسلي إن لم يطابق باركود)
    FUNCTION ITEM_BY_CODE (p_code IN VARCHAR2) RETURN NUMBER;

    -- استلام كمية إلى المخزن (توريد جديد)
    PROCEDURE RECEIVE (
        p_item_id IN NUMBER,
        p_qty     IN NUMBER,
        p_date    IN DATE     DEFAULT SYSDATE,
        p_remarks IN VARCHAR2 DEFAULT NULL
    );

    -- صرف كمية لموظف أو لشخص (p_person_name لمن ليس موظفًا)
    PROCEDURE ISSUE (
        p_item_id         IN NUMBER,
        p_qty             IN NUMBER,
        p_employee_id     IN NUMBER   DEFAULT NULL,
        p_person_name     IN VARCHAR2 DEFAULT NULL,
        p_authorized_by   IN NUMBER   DEFAULT NULL,
        p_expected_return IN DATE     DEFAULT NULL,
        p_date            IN DATE     DEFAULT SYSDATE,
        p_remarks         IN VARCHAR2 DEFAULT NULL
    );

    -- إرجاع كمية مصروفة إلى المخزن
    PROCEDURE RETURN_ITEM (
        p_item_id     IN NUMBER,
        p_qty         IN NUMBER,
        p_employee_id IN NUMBER   DEFAULT NULL,
        p_person_name IN VARCHAR2 DEFAULT NULL,
        p_date        IN DATE     DEFAULT SYSDATE,
        p_remarks     IN VARCHAR2 DEFAULT NULL
    );

    -- تسوية الرصيد بعد الجرد (الرصيد الجديد، والسبب إلزامي)
    PROCEDURE ADJUST (
        p_item_id IN NUMBER,
        p_new_qty IN NUMBER,
        p_remarks IN VARCHAR2,
        p_date    IN DATE DEFAULT SYSDATE
    );

END MOINFO_STD;
/

CREATE OR REPLACE PACKAGE BODY MOINFO_STD AS

    g_in_move BOOLEAN := FALSE;

    FUNCTION IN_MOVE RETURN BOOLEAN IS
    BEGIN
        RETURN g_in_move;
    END IN_MOVE;

    FUNCTION CAN_MOVE RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN MOINFO_SEC.HAS_ROLE('STD', 'USER') THEN 'Y' ELSE 'N' END;
    END CAN_MOVE;

    FUNCTION IS_MANAGER RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN MOINFO_SEC.HAS_ROLE('STD', 'MANAGER') THEN 'Y' ELSE 'N' END;
    END IS_MANAGER;

    FUNCTION ITEM_BY_CODE (p_code IN VARCHAR2) RETURN NUMBER IS
        l_id NUMBER;
    BEGIN
        SELECT MIN(ITEM_ID) INTO l_id FROM MOINFO_STD_ITEMS WHERE UPPER(BARCODE) = UPPER(TRIM(p_code));
        IF l_id IS NULL THEN
            SELECT MIN(ITEM_ID) INTO l_id FROM MOINFO_STD_ITEMS WHERE UPPER(SERIAL_NO) = UPPER(TRIM(p_code));
        END IF;
        RETURN l_id;
    END ITEM_BY_CODE;

    -- ينفّذ الحركة: يقفل سطر المعدة، ويحسب الرصيد الجديد، ويحدّثه، ويسجّل الحركة
    PROCEDURE MOVE (
        p_item_id         IN NUMBER,
        p_type            IN VARCHAR2,
        p_change          IN NUMBER,
        p_employee_id     IN NUMBER,
        p_person_name     IN VARCHAR2,
        p_authorized_by   IN NUMBER,
        p_expected_return IN DATE,
        p_date            IN DATE,
        p_remarks         IN VARCHAR2
    ) IS
        l_qty    NUMBER;
        l_active VARCHAR2(1);
        l_new    NUMBER;
    BEGIN
        BEGIN
            SELECT QTY_IN_STOCK, IS_ACTIVE INTO l_qty, l_active
              FROM MOINFO_STD_ITEMS
             WHERE ITEM_ID = p_item_id
               FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20070, 'المعدة غير موجودة');
        END;
        IF l_active = 'N' AND p_type <> 'ADJUST' THEN
            RAISE_APPLICATION_ERROR(-20071, 'المعدة غير نشطة');
        END IF;

        l_new := l_qty + p_change;
        IF l_new < 0 THEN
            RAISE_APPLICATION_ERROR(-20072, 'الكمية المطلوبة أكبر من الرصيد في المخزن (' || l_qty || ')');
        END IF;

        g_in_move := TRUE;
        UPDATE MOINFO_STD_ITEMS SET QTY_IN_STOCK = l_new WHERE ITEM_ID = p_item_id;
        g_in_move := FALSE;

        INSERT INTO MOINFO_STD_MOVEMENTS (
            ITEM_ID, MOVEMENT_TYPE, MOVEMENT_DATE, QTY_CHANGE, BALANCE_AFTER, EMPLOYEE_ID, PERSON_NAME,
            AUTHORIZED_BY_ID, EXPECTED_RETURN_DATE, REMARKS)
        VALUES (
            p_item_id, p_type, NVL(p_date, SYSDATE), p_change, l_new, p_employee_id, TRIM(p_person_name),
            p_authorized_by, p_expected_return, p_remarks);
    EXCEPTION
        WHEN OTHERS THEN
            g_in_move := FALSE;
            RAISE;
    END MOVE;

    PROCEDURE CHECK_QTY (p_qty IN NUMBER) IS
    BEGIN
        IF p_qty IS NULL OR p_qty <= 0 THEN
            RAISE_APPLICATION_ERROR(-20073, 'الكمية يجب أن تكون أكبر من صفر');
        END IF;
    END CHECK_QTY;

    PROCEDURE CHECK_CAN_MOVE IS
    BEGIN
        IF CAN_MOVE = 'N' THEN
            RAISE_APPLICATION_ERROR(-20074, 'لا تملك صلاحية تسجيل حركات المخزن');
        END IF;
    END CHECK_CAN_MOVE;

    PROCEDURE RECEIVE (
        p_item_id IN NUMBER,
        p_qty     IN NUMBER,
        p_date    IN DATE     DEFAULT SYSDATE,
        p_remarks IN VARCHAR2 DEFAULT NULL
    ) IS
    BEGIN
        CHECK_CAN_MOVE;
        CHECK_QTY(p_qty);
        MOVE(p_item_id, 'IN', p_qty, NULL, NULL, NULL, NULL, p_date, p_remarks);
    END RECEIVE;

    PROCEDURE ISSUE (
        p_item_id         IN NUMBER,
        p_qty             IN NUMBER,
        p_employee_id     IN NUMBER   DEFAULT NULL,
        p_person_name     IN VARCHAR2 DEFAULT NULL,
        p_authorized_by   IN NUMBER   DEFAULT NULL,
        p_expected_return IN DATE     DEFAULT NULL,
        p_date            IN DATE     DEFAULT SYSDATE,
        p_remarks         IN VARCHAR2 DEFAULT NULL
    ) IS
    BEGIN
        CHECK_CAN_MOVE;
        CHECK_QTY(p_qty);
        IF p_employee_id IS NULL AND TRIM(p_person_name) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20075, 'حدد الموظف أو اسم المستلم');
        END IF;
        IF p_expected_return IS NOT NULL AND p_expected_return < TRUNC(NVL(p_date, SYSDATE)) THEN
            RAISE_APPLICATION_ERROR(-20076, 'تاريخ الإرجاع المتوقع يسبق تاريخ الصرف');
        END IF;
        MOVE(p_item_id, 'OUT', -p_qty, p_employee_id, p_person_name, p_authorized_by, p_expected_return, p_date, p_remarks);
    END ISSUE;

    PROCEDURE RETURN_ITEM (
        p_item_id     IN NUMBER,
        p_qty         IN NUMBER,
        p_employee_id IN NUMBER   DEFAULT NULL,
        p_person_name IN VARCHAR2 DEFAULT NULL,
        p_date        IN DATE     DEFAULT SYSDATE,
        p_remarks     IN VARCHAR2 DEFAULT NULL
    ) IS
        l_out NUMBER;
    BEGIN
        CHECK_CAN_MOVE;
        CHECK_QTY(p_qty);
        IF p_employee_id IS NULL AND TRIM(p_person_name) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20075, 'حدد الموظف أو اسم المستلم');
        END IF;
        -- لا يُرجع أكثر مما لديه
        SELECT NVL(-SUM(QTY_CHANGE), 0) INTO l_out
          FROM MOINFO_STD_MOVEMENTS
         WHERE ITEM_ID = p_item_id
           AND MOVEMENT_TYPE IN ('OUT', 'RETURN')
           AND ((p_employee_id IS NOT NULL AND EMPLOYEE_ID = p_employee_id)
             OR (p_employee_id IS NULL AND EMPLOYEE_ID IS NULL AND UPPER(PERSON_NAME) = UPPER(TRIM(p_person_name))));
        IF p_qty > l_out THEN
            RAISE_APPLICATION_ERROR(-20077, 'الكمية المُرجعة أكبر من المصروف لهذا المستلم (' || l_out || ')');
        END IF;
        MOVE(p_item_id, 'RETURN', p_qty, p_employee_id, p_person_name, NULL, NULL, p_date, p_remarks);
    END RETURN_ITEM;

    PROCEDURE ADJUST (
        p_item_id IN NUMBER,
        p_new_qty IN NUMBER,
        p_remarks IN VARCHAR2,
        p_date    IN DATE DEFAULT SYSDATE
    ) IS
        l_qty NUMBER;
    BEGIN
        IF IS_MANAGER = 'N' THEN
            RAISE_APPLICATION_ERROR(-20078, 'التسوية لمشرف المخزن');
        END IF;
        IF p_new_qty IS NULL OR p_new_qty < 0 THEN
            RAISE_APPLICATION_ERROR(-20079, 'الرصيد الجديد يجب ألا يكون سالبًا');
        END IF;
        IF TRIM(p_remarks) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20080, 'اكتب سبب التسوية');
        END IF;
        SELECT QTY_IN_STOCK INTO l_qty FROM MOINFO_STD_ITEMS WHERE ITEM_ID = p_item_id;
        IF p_new_qty = l_qty THEN
            RAISE_APPLICATION_ERROR(-20081, 'الرصيد الجديد مساوٍ للرصيد الحالي');
        END IF;
        MOVE(p_item_id, 'ADJUST', p_new_qty - l_qty, NULL, NULL, NULL, NULL, p_date, p_remarks);
    END ADJUST;

END MOINFO_STD;
/


