CREATE OR REPLACE VIEW MOINFO_STD_V_MOVEMENTS AS
SELECT m.MOVEMENT_ID,
       m.ITEM_ID,
       i.BARCODE,
       i.ITEM_NAME,
       m.MOVEMENT_TYPE,
       CASE m.MOVEMENT_TYPE
           WHEN 'IN'     THEN 'استلام'
           WHEN 'OUT'    THEN 'صرف'
           WHEN 'RETURN' THEN 'إرجاع'
           WHEN 'ADJUST' THEN 'تسوية'
       END AS MOVEMENT_TYPE_AR,
       m.MOVEMENT_DATE,
       m.QTY_CHANGE,
       ABS(m.QTY_CHANGE) AS QTY,
       m.BALANCE_AFTER,
       m.EMPLOYEE_ID,
       e.EMPLOYEE_NO,
       NVL(e.NAME_AR, m.PERSON_NAME) AS RECIPIENT_AR,
       m.PERSON_NAME,
       m.AUTHORIZED_BY_ID,
       a.NAME_AR AS AUTHORIZED_BY_AR,
       m.EXPECTED_RETURN_DATE,
       m.REMARKS,
       m.CREATED_BY,
       NVL(u.DISPLAY_NAME, m.CREATED_BY) AS CREATED_BY_NAME,
       m.CREATED_AT
  FROM MOINFO_STD_MOVEMENTS m
  JOIN MOINFO_STD_ITEMS i      ON i.ITEM_ID = m.ITEM_ID
  LEFT JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = m.EMPLOYEE_ID
  LEFT JOIN MOINFO_EMPLOYEES a ON a.EMPLOYEE_ID = m.AUTHORIZED_BY_ID
  LEFT JOIN MOINFO_USERS u     ON u.USERNAME = m.CREATED_BY;

-- ما لدى كل مستلم من كل معدة (المصروف ناقص المُرجع)، مع آخر صرف وتاريخ الإرجاع المتوقع
CREATE OR REPLACE VIEW MOINFO_STD_V_OUTSTANDING AS
SELECT x.ITEM_ID,
       i.BARCODE,
       i.ITEM_NAME,
       x.EMPLOYEE_ID,
       e.EMPLOYEE_NO,
       NVL(e.NAME_AR, x.PERSON_KEY) AS RECIPIENT_AR,
       e.PHONE_EXT,
       x.QTY_OUT,
       x.LAST_ISSUE_DATE,
       x.EXPECTED_RETURN_DATE,
       TRUNC(SYSDATE) - TRUNC(x.LAST_ISSUE_DATE) AS DAYS_OUT,
       CASE
           WHEN x.EXPECTED_RETURN_DATE IS NOT NULL AND x.EXPECTED_RETURN_DATE < TRUNC(SYSDATE) THEN 'Y'
           WHEN x.EXPECTED_RETURN_DATE IS NULL
                AND TRUNC(SYSDATE) - TRUNC(x.LAST_ISSUE_DATE)
                    > TO_NUMBER(NVL((SELECT SETTING_VALUE FROM MOINFO_SETTINGS WHERE SETTING_KEY = 'STD_OVERDUE_DAYS'), '7'))
           THEN 'Y'
           ELSE 'N'
       END AS IS_OVERDUE
  FROM (SELECT ITEM_ID,
               EMPLOYEE_ID,
               CASE WHEN EMPLOYEE_ID IS NULL THEN UPPER(PERSON_NAME) END AS PERSON_KEY,
               -SUM(QTY_CHANGE) AS QTY_OUT,
               MAX(CASE WHEN MOVEMENT_TYPE = 'OUT' THEN MOVEMENT_DATE END) AS LAST_ISSUE_DATE,
               MAX(EXPECTED_RETURN_DATE) KEEP (DENSE_RANK LAST ORDER BY CASE WHEN MOVEMENT_TYPE = 'OUT' THEN MOVEMENT_DATE END NULLS FIRST)
                   AS EXPECTED_RETURN_DATE
          FROM MOINFO_STD_MOVEMENTS
         WHERE MOVEMENT_TYPE IN ('OUT', 'RETURN')
         GROUP BY ITEM_ID, EMPLOYEE_ID, CASE WHEN EMPLOYEE_ID IS NULL THEN UPPER(PERSON_NAME) END
        HAVING -SUM(QTY_CHANGE) > 0) x
  JOIN MOINFO_STD_ITEMS i      ON i.ITEM_ID = x.ITEM_ID
  LEFT JOIN MOINFO_EMPLOYEES e ON e.EMPLOYEE_ID = x.EMPLOYEE_ID;

CREATE OR REPLACE VIEW MOINFO_STD_V_ITEMS AS
SELECT i.ITEM_ID,
       i.BARCODE,
       i.ITEM_NAME,
       i.SERIAL_NO,
       i.PRODUCT_TYPE_ID,
       t.NAME_AR AS PRODUCT_TYPE_AR,
       i.BRAND_ID,
       b.NAME AS BRAND_NAME,
       i.MODEL_ID,
       m.NAME AS MODEL_NAME,
       i.STATUS_ID,
       st.LOOKUP_CODE AS STATUS_CODE,
       st.NAME_AR AS STATUS_AR,
       i.LOCATION_ID,
       lo.NAME_AR AS LOCATION_AR,
       i.BIN_ID,
       bn.NAME_AR AS BIN_AR,
       i.QTY_IN_STOCK,
       NVL(o.QTY_OUT, 0) AS QTY_OUT,
       i.QTY_IN_STOCK + NVL(o.QTY_OUT, 0) AS QTY_TOTAL,
       i.MIN_QTY,
       CASE WHEN i.MIN_QTY IS NOT NULL AND i.QTY_IN_STOCK <= i.MIN_QTY THEN 'Y' ELSE 'N' END AS IS_LOW,
       i.WARRANTY_END,
       i.DESCRIPTION,
       i.IS_ACTIVE
  FROM MOINFO_STD_ITEMS i
  LEFT JOIN MOINFO_CAT_PRODUCT_TYPES t ON t.PRODUCT_TYPE_ID = i.PRODUCT_TYPE_ID
  LEFT JOIN MOINFO_CAT_BRANDS b        ON b.BRAND_ID = i.BRAND_ID
  LEFT JOIN MOINFO_CAT_MODELS m        ON m.MODEL_ID = i.MODEL_ID
  LEFT JOIN MOINFO_LOOKUPS st          ON st.LOOKUP_ID = i.STATUS_ID
  LEFT JOIN MOINFO_LOOKUPS lo          ON lo.LOOKUP_ID = i.LOCATION_ID
  LEFT JOIN MOINFO_LOOKUPS bn          ON bn.LOOKUP_ID = i.BIN_ID
  LEFT JOIN (SELECT ITEM_ID, SUM(QTY_OUT) AS QTY_OUT FROM MOINFO_STD_V_OUTSTANDING GROUP BY ITEM_ID) o
         ON o.ITEM_ID = i.ITEM_ID;


